// Токены общей рамки фокуса.
//
// Рамку рисуют widget.DrawFocusRing (диалоги и кнопки с Button.FocusRing) и
// desktop.PaintFocusRing (элементы панели задач): профиль объявляет вид один раз,
// и клавиатурный фокус выглядит одинаково и в диалоге, и на панели. Профиль,
// который токенов не объявляет, остаётся прежним: контур цвета текста элемента
// и внутренний контрастный; толщина наружного контура — своя у каждого
// потребителя (две точки в диалогах, одна на панели задач).
const (
	// KeyFocusRingWidth — толщина наружного контура рамки в логических
	// пикселях (внутренний контрастный контур всегда в один пиксель).
	KeyFocusRingWidth Key = "focus.ring.width"
	// KeyFocusRing — цвет наружного контура. Не задан (A=0) — цвет текста
	// элемента.
	KeyFocusRing Key = "focus.ring"
)
