// surface.go — рисование в буфер, предоставленный потребителем, вместо
// собственного back-буфера канваса (см. ROTATION NOTE ниже — ротация
// нескольких буферов НЕ реализована, только один буфер за раз).
package engine

import "fmt"

// SetSurface переключает back-буфер движка на память, предоставленную
// потребителем: место, куда пишет растеризатор, становится тем же местом,
// откуда потребитель дальше берёт кадр — вместо собственного буфера
// движка, который потребитель после каждого кадра копировал бы к себе.
//
// pix — плотный буфер потребителя; stride — шаг строки в байтах (может
// быть больше физической ширины холста ×4, если у потребителя своя
// раскладка памяти, например построчное выравнивание DIB); f — порядок
// каналов буфера (см. PixelFormat) — действует так же, как формат,
// заданный через SetPixelFormat, но именно для ЭТОГО буфера.
//
// pix == nil возвращает движок к собственному буферу (stride и f в этом
// случае игнорируются).
//
// Размер и шаг проверяются здесь: буфер должен вмещать h строк по stride
// байт, последняя строка — минимум w×4 байт (физический размер холста).
// Несоответствие — ошибка с указанием требуемого размера, а не паника или
// тихая порча чужой памяти за её пределами.
//
// front-буфер (нужен для побайтового diff между кадрами — dirty tiles)
// ВСЕГДА остаётся внутренним, собственным буфером движка: содержимое
// чужой памяти между кадрами потребитель волен менять как угодно (отдать
// на экран, отдать следующему потребителю), и сравнивать её саму с собой
// между вызовами Frame было бы неверно.
//
// Вызывать в любой момент; после переключения буфера следующий кадр
// перерисуется целиком (новый буфер не совпадает с front ни одним байтом).
func (e *Engine) SetSurface(pix []byte, stride int, f PixelFormat) error {
	if pix == nil {
		e.frameMu.Lock() // буфер меняется — ждём конца текущего кадра
		e.canvas.useOwnBack()
		e.frameMu.Unlock()
		e.Invalidate()
		return nil
	}
	if f != FormatRGBA && f != FormatBGRX {
		return fmt.Errorf("engine: SetSurface: неизвестный формат %d", uint8(f))
	}

	e.frameMu.Lock()

	w, h := e.canvas.W, e.canvas.H
	rowBytes := w * 4
	if stride < rowBytes {
		e.frameMu.Unlock()
		return fmt.Errorf(
			"engine: SetSurface: stride %d меньше ширины строки %d байт (физический размер холста %dx%d)",
			stride, rowBytes, w, h)
	}
	need := rowBytes
	if h > 1 {
		need = stride*(h-1) + rowBytes
	}
	if h <= 0 {
		need = 0
	}
	if len(pix) < need {
		e.frameMu.Unlock()
		return fmt.Errorf(
			"engine: SetSurface: буфер длиной %d байт мал для холста %dx%d при stride=%d (нужно ≥ %d)",
			len(pix), w, h, stride, need)
	}

	e.canvas.setExternalBack(pix, stride, f)
	e.frameMu.Unlock()
	e.Invalidate() // новый буфер не совпадает с front ни одним байтом — перерисовать всё
	return nil
}
