// moveapply.go — применение объявленных переносов к переднему буферу.
//
// Перетаскивание окна не меняет пиксели, а переносит их. Виджет объявляет
// это (widget.NotifyMove), движок кладёт объявление в кадр, и потребитель
// выполняет копирование вместо приёма картинки заново.
//
// Но одного объявления мало. Дифф сравнивает НОВЫЙ задний буфер со СТАРЫМ
// передним: на старом месте окна ещё нет, на новом — уже есть, и оба места
// уезжают тайлами. Потребитель получал и команду переноса, и все пиксели —
// то есть платил ровно столько же, сколько без переноса.
//
// Поэтому перенос применяется к переднему буферу ДО диффа: передний буфер
// приводится в то состояние, в котором окажется буфер потребителя после
// копирования. Дальше дифф сравнивает уже с ним и оставляет только то, что
// действительно отличается, — кайму, тень, изменившееся содержимое.

package engine

import (
	"image"

	"github.com/oops1/headless-gui/v4/output"
	"github.com/oops1/headless-gui/v4/widget"
)

// widgetMove — объявление переноса в логических координатах (копия
// widget.MoveNotice, чтобы engine не зависел от его формы). Те же поля, что у
// переноса кадра: холст применяет объявления к переднему буферу как есть.
type widgetMove = output.MoveRegion

// noteMove принимает объявление от дерева виджетов. Регистрируется в New.
//
// Приёмник получает объявления ВСЕГО процесса, поэтому чужие надо отсеять.
// Перенос, выполненный по чужому объявлению, портит передний буфер: движок
// скопирует пиксели с места, где ничего не переезжало, отдаст потребителю
// команду копии — и тот покажет чужой прямоугольник, пока следующий дифф не
// исправит его тайлами.
//
// Отсеиваются двумя способами, и порядок важен:
//
//  1. По виджету, если он назван. Это единственный точный признак: у двух
//     движков одного разрешения (две сессии в одном процессе — обычное дело)
//     координаты совпадают, и по ним своё от чужого не отличить.
//  2. По холсту, если виджет не назван. Так приходят объявления из
//     NotifyMove, который потребитель зовёт напрямую: чьи они — неизвестно,
//     и остаётся проверить, лежат ли они хотя бы на этом экране.
func (e *Engine) noteMove(n widget.MoveNotice) {
	if n.Rect.Empty() {
		return
	}
	e.mu.RLock()
	canvas, root := e.canvas, e.root
	e.mu.RUnlock()
	if canvas == nil {
		return
	}

	if n.Widget != nil {
		if root == nil || !widgetInTree(root, n.Widget) {
			return
		}
	} else {
		// Границы холста в логических координатах — тех же, в которых живут
		// виджеты и приходит объявление.
		lw, lh := canvas.LogicalSize()
		screen := image.Rect(0, 0, lw, lh)
		src := image.Rect(n.From.X, n.From.Y, n.From.X+n.Rect.Dx(), n.From.Y+n.Rect.Dy())
		if !n.Rect.Overlaps(screen) && !src.Overlaps(screen) {
			return
		}
	}

	e.moveMu.Lock()
	// Список ограничен: движок, который не рисует, копил бы объявления
	// вечно — перетаскивание объявляет их шестьдесят раз в секунду, а
	// созданный и оставленный движок (окно свёрнуто, кадры не запрашивают)
	// их не разбирает. Лишние отбрасываются, а не вытесняют старые:
	// потерянный перенос — это лишние тайлы, а не порча картинки, и лучше
	// потерять поздние, чем те, к которым уже привязано состояние буфера.
	if len(e.pendingMoves) < maxPendingMoves {
		e.pendingMoves = append(e.pendingMoves, widgetMove{From: n.From, Rect: n.Rect})
	}
	e.moveMu.Unlock()
}

// maxPendingMoves — сколько объявлений движок держит между кадрами.
//
// Кадр всё равно возьмёт лишь непересекающиеся, а их на экране помещается
// немного; шестьдесят четыре с запасом покрывают самый бурный кадр.
const maxPendingMoves = 64

// widgetInTree ищет виджет в дереве.
//
// Обход, а не ссылка на родителя: её у виджетов нет, и заводить её ради
// одной проверки — большая перестройка. Цена невелика: поиск идёт только на
// объявленный перенос (шаг перетаскивания, десятки раз в секунду), а дерево
// экрана — сотни узлов.
//
// Глубина ограничена, как у остальных обходов (tooDeep): приёмник переносов
// общий на процесс, и цикл в Children() дерева любого движка иначе валил
// переполнением стека перетаскивание окна в другом.
func widgetInTree(node, target widget.Widget) bool {
	return widgetInTreeAt(node, target, 0)
}

func widgetInTreeAt(node, target widget.Widget, depth int) bool {
	if node == nil || tooDeep(depth) {
		return false
	}
	if node == target {
		return true
	}
	for _, child := range node.Children() {
		if widgetInTreeAt(child, target, depth+1) {
			return true
		}
	}
	return false
}

// takeMoves забирает накопленные объявления и очищает список.
func (e *Engine) takeMoves() []widgetMove {
	e.moveMu.Lock()
	out := e.pendingMoves
	e.pendingMoves = nil
	e.moveMu.Unlock()
	return out
}
