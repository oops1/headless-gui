package engine

import "image"

// Зернистый шум поверх слоя — последний штрих acrylic Windows 10.
//
// Размытая подкрашенная подложка сама по себе гладкая; зерно в пару
// процентов яркости разбивает градиенты (иначе на тёмной панели видны
// ступени 8-битных оттенков) и даёт то самое ощущение «пластика с
// фактурой». Хранить для этого текстуру незачем: значение шума — хеш
// координат пикселя, поэтому оно
//
//   - детерминировано: один и тот же кадр даёт те же байты, дельта-тайлы не
//     «мерцают», а golden-снимки стабильны;
//   - привязано к пикселям кадра, а не к области: соседние слои и сдвиг слоя
//     не меняют зерно под ним;
//   - не требует памяти и не повторяется заметным узором.

// DrawNoise наносит на область r монохромный шум амплитудой amount (доля
// полной шкалы яркости: 0.02 — отклонение до ±2 %, то есть около ±5 уровней).
//
// r — ЛОГИЧЕСКИЕ координаты. Отсечение канваса, в том числе скруглённое,
// уважается. Нулевая или отрицательная амплитуда, пустая область — ничего не
// делает. Каналы клампятся по альфе пикселя, поэтому на прозрачном буфере
// premultiplied-инвариант (R,G,B ≤ A) не нарушается.
func (c *Canvas) DrawNoise(r image.Rectangle, amount float64) {
	if amount <= 0 {
		return
	}
	area := c.clampRect(c.sRect(r))
	if area.Empty() {
		return
	}
	if amount > 1 {
		amount = 1
	}
	// Пик отклонения в уровнях; шум — сумма двух равномерных (треугольное
	// распределение), поэтому крупные отклонения редки и зерно мягкое.
	peak := amount * 255
	const span = 255.0 // размах суммы двух байт минус 255: [-255, 255]
	scale := peak / span

	c.markImage(area)
	for y := area.Min.Y; y < area.Max.Y; y++ {
		x0, x1, ok := c.round.spanX(y, area.Min.X, area.Max.X)
		if !ok {
			continue
		}
		off := c.back.PixOffset(x0, y)
		row := c.back.Pix[off : off+(x1-x0)*4]
		for i, x := 0, x0; i+3 < len(row); i, x = i+4, x+1 {
			a := int(row[i+3])
			if a == 0 {
				continue
			}
			h := noiseHash(uint32(x), uint32(y))
			d := int(float64(int(h&0xFF)+int(h>>8&0xFF)-255) * scale)
			if d == 0 {
				continue
			}
			for ch := 0; ch < 3; ch++ {
				v := int(row[i+ch]) + d
				if v < 0 {
					v = 0
				} else if v > a {
					v = a
				}
				row[i+ch] = uint8(v)
			}
		}
	}
}

// noiseHash — быстрый целочисленный хеш пары координат (в духе murmur3
// finalizer): достаточно «белый» для зерна и без таблиц.
func noiseHash(x, y uint32) uint32 {
	h := x*0x9E3779B1 ^ y*0x85EBCA77
	h ^= h >> 15
	h *= 0x2C1B3C6D
	h ^= h >> 12
	h *= 0x297A2D39
	h ^= h >> 15
	return h
}
