package engine

import "testing"

// BenchmarkEngineNew — стоимость создания ДОПОЛНИТЕЛЬНОГО движка в процессе.
// Это горячий путь hosted-режима: движок создаётся на каждый нативный
// модальный диалог и на каждую оторванную док-панель, то есть на каждое
// ОТКРЫТИЕ диалога пользователем. Кэш файлов шрифтов (readFontFile) снимает
// с этого пути дисковый ввод-вывод.
func BenchmarkEngineNew(b *testing.B) {
	e := New(320, 240, 30) // прогрев кэша файлов, как в реальном процессе
	_ = e
	b.ReportAllocs()
	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		eng := New(320, 240, 30)
		_ = eng
	}
}
