package engine

// loop.go — цикл кадров движка (ADR-0011, задача 7.3): горутину цикла, темп
// и доставку кадров, повреждение кадра и рендер по запросу, очередь Post и
// таймеры ведёт core/loop (loop.Loop, поле e.lp). Здесь — публичные методы
// цикла Engine, которые отдают работу ему, алиасы его типов (Timer, Pacing,
// FrameSink — открытый API не меняется) и адаптер loopHost: то, что цикл
// берёт у движка (кадр, анимации, нужен ли кадр без инвалидации, полный кадр,
// граница сбоев, профиль движения, масштаб).

import (
	"time"

	"github.com/oops1/headless-gui/v4/core/loop"
	"github.com/oops1/headless-gui/v4/output"
	"github.com/oops1/headless-gui/v4/widget"
)

// Pacing — кто решает, когда готовится кадр.
type Pacing = loop.Pacing

const (
	// PacingTicker — внутренний тикер FPS, как было всегда.
	PacingTicker = loop.PacingTicker
	// PacingExternal — кадры готовятся только по RequestFrame.
	PacingExternal = loop.PacingExternal
)

// FrameSink — сток готовых кадров.
//
// Альтернатива каналу Frames(), а не замена: канал продолжает работать. Сток
// получает кадр СИНХРОННО, в горутине рендера, и потому не может его
// потерять — в отличие от канала, который при переполнении молча выбрасывал
// кадр.
type FrameSink = loop.FrameSink

// Timer — ручка отложенного или повторяющегося вызова, созданного After или
// Every. Все методы безопасны из любой горутины.
type Timer = loop.Timer

// loopHost — движок глазами цикла (loop.Host). Методы зовутся без замков
// пакета loop.
type loopHost struct{ e *Engine }

var _ loop.Host = loopHost{}

// RenderFrame — кадр (сам берёт frameMu).
func (h loopHost) RenderFrame() output.Frame { return h.e.renderFrame() }

// StepAnimations шагает анимации цикла этого движка.
func (h loopHost) StepAnimations(now time.Time) { widget.StepAnimationsFor(h.e, now) }

// AnimationNeeded — кадр без инвалидации (invalidate.go).
func (h loopHost) AnimationNeeded(interval time.Duration) bool { return h.e.animationNeeded(interval) }

// FullFramePending — следующий кадр полный (fullframe.go).
func (h loopHost) FullFramePending() bool { return h.e.fullFramePending() }

// GuardCall — граница сбоев (failure.go).
func (h loopHost) GuardCall(where string, fn func()) { h.e.guardCall(where, fn) }

// MotionScope — профиль движения на горутине вызывающего (motionprofile.go).
func (h loopHost) MotionScope() func() { return h.e.motionScope() }

// BindLoop — горутина цикла шагает анимации этого движка (GG-68): у
// вторичного движка диалога свои обработчики и своя горутина.
func (h loopHost) BindLoop() func() { return widget.BindAnimationLoop(h.e) }

// Scale — HiDPI-масштаб.
func (h loopHost) Scale() float64 { return h.e.Scale() }

// OnInvalidateAll — новое поколение записи команд (cmdpath.go): кадр,
// заставший полное повреждение, обязан застать и его.
func (h loopHost) OnInvalidateAll() {
	if h.e.rec != nil {
		h.e.rec.Invalidate()
	}
}

// ── Внутренние помощники движка поверх цикла ───────────────────────────────

// runPosted выполняет накопленные вызовы Post (RenderOnce, RenderFrameNow у
// незапущенного движка).
func (e *Engine) runPosted() { e.lp.RunPosted() }

// callOnLoop выполняет fn на горутине движка и ждёт (мост доступности).
func (e *Engine) callOnLoop(fn func()) { e.lp.CallOnLoop(fn) }

// frameInterval — пауза между кадрами с учётом SetMaxFPS.
func (e *Engine) frameInterval() time.Duration { return e.lp.FrameInterval() }

// deliver отдаёт кадр стоку и в канал.
func (e *Engine) deliver(frame output.Frame) { e.lp.Deliver(frame) }

// pacingIsExternal — кадры только по RequestFrame (PacingExternal).
func (e *Engine) pacingIsExternal() bool { return e.lp.Pacing() == PacingExternal }

// Post ставит fn в очередь на выполнение в горутине кадра.
//
// Функции выполняются в порядке постановки, в начале очередного прохода
// цикла кадров — до отрисовки, так что изменения дерева попадают в тот же
// кадр. Из fn можно звать что угодно: движок к этому моменту своих замков не
// держит.
//
// Post безопасен из любой горутины, в том числе из самой горутины кадра: в
// этом случае fn выполнится на СЛЕДУЮЩЕМ проходе, а не сразу. Рекурсия из fn
// поэтому не зацикливает кадр.
//
// Гарантия (GG-68): у запущенного движка функции из Post выполняются на той же
// горутине, что и обработчики ввода, — на горутине цикла кадров — и под
// window.Run, и в webstream. Окно ставит события ОС в эту же очередь, а
// анимации шагает цикл своего движка. Гонки «обработчик против функции из Post»
// поэтому нет, и менять виджеты из fn можно без замков. Потребитель, который
// при запущенном движке сам зовёт Send* со своей горутины, эту гарантию теряет:
// Send* выполняются там, где их позвали, — такой ввод тоже нужно отдавать через
// Post.
//
// Ловушка: без Start() очередь разбирать некому — тогда её разбирают
// RenderOnce и RenderFrameNow, то есть она всё равно опустошается, но в тот
// момент, когда приложение само просит кадр. Движок, который не запущен и
// кадров не рисует, накопленное не выполнит.
func (e *Engine) Post(fn func()) {
	e.lp.Post(fn)
}

// Flush выполняет всё, что стоит в очереди Post, и возвращается, когда очередь
// разобрана.
//
// Нужен тестам приложения: подождать, пока отложенная работа выполнится, не
// рисуя ради этого кадр (RenderOnce на каждое ожидание обходится дорого).
//
//   - Движок не запущен — очередь разбирается здесь же, на вызывающей
//     горутине, повторно, пока функции ставят в неё новые (не больше
//     flushRounds проходов).
//   - Движок запущен — очередь разбирает только цикл кадров, и Flush ждёт,
//     пока он дойдёт до поставленной следом отметки. Работа выполняется на
//     горутине движка, а не на вызывающей.
//
// Из самой горутины движка (обработчик, функция из Post) Flush сразу
// возвращается: ждать завершения очереди, в которой стоишь сам, значит
// повиснуть. После Stop ожидание прерывается.
func (e *Engine) Flush() {
	e.lp.Flush()
}

// After выполняет fn на горутине движка через d и возвращает ручку, которой
// вызов можно отменить.
//
// fn исполняется тем же путём, что и Post: на горутине цикла кадров, перед
// отрисовкой очередного кадра, без замков движка. Дерево виджетов принадлежит
// движку, и трогать его из горутины системного таймера значило бы гонку с
// обходом в root.Draw — поэтому таймер лишь ставит вызов в очередь, а сам
// вызов делает движок.
//
// Пока таймер ждёт, он не держит горутин: системный таймер просыпается один раз
// и сразу отдаёт работу движку. Отмена после срабатывания, но до выполнения
// тоже работает — fn, уже стоящий в очереди, проверяет флаг и не выполняется.
//
// Если движок уже остановлен или fn пуст, возвращается уже остановленный
// таймер: ничего не заводится. Остановка движка гасит все его таймеры.
// d <= 0 даёт вызов на ближайшем проходе цикла, как Post.
//
// Ловушка та же, что у Post: без Start() очередь разбирают лишь RenderOnce,
// RenderFrameNow и Flush, поэтому у незапущенного движка fn выполнится в тот
// момент, когда приложение само попросит кадр.
func (e *Engine) After(d time.Duration, fn func()) *Timer {
	return e.lp.After(d, fn)
}

// Every повторяет fn на горутине движка каждые d, пока таймер не остановят
// или не остановят движок.
//
// Следующий запуск планируется ПОСЛЕ того, как fn вернулся, то есть между
// концом одного вызова и началом следующего проходит d. Так медленный
// обработчик замедляет повтор, а не копит очередь: time.Ticker слал бы тики
// независимо от обработчика, и после долгой паузы вызовы шли бы подряд, один
// за другим. Цена — период дрейфует на время работы fn; для автосохранения и
// повтора поиска это то, что нужно.
//
// fn может остановить собственный таймер: после возврата следующий запуск не
// планируется. Период меньше миллисекунды округляется вверх до миллисекунды.
// Остальное — как у After.
func (e *Engine) Every(d time.Duration, fn func()) *Timer {
	return e.lp.Every(d, fn)
}

// SetPacing выбирает, кто задаёт темп.
//
// При PacingExternal внутренний тикер кадры не запускает — но продолжает
// продвигать анимации: иначе анимация, начатая приложением, замерла бы до
// следующего RequestFrame и дёргалась бы рывками.
func (e *Engine) SetPacing(p Pacing) {
	e.lp.SetPacing(p)
}

// Pacing сообщает текущий режим темпа.
func (e *Engine) Pacing() Pacing {
	return e.lp.Pacing()
}

// SetFrameSink задаёт сток кадров (nil — снять).
func (e *Engine) SetFrameSink(s FrameSink) {
	e.lp.SetFrameSink(s)
}

// RequestFrame просит подготовить кадр: сток готов его принять.
//
// Имеет смысл при PacingExternal; при PacingTicker просто помечает кадр
// нужным, как обычная инвалидация, — чтобы переключение режима не требовало
// переписывать вызовы.
//
// Вызов не блокирует: он лишь поднимает флаг, а кадр готовит горутина
// рендера. Несколько вызовов подряд дают один кадр — сток всё равно не
// успеет принять больше.
func (e *Engine) RequestFrame() {
	e.lp.RequestFrame()
}

// SetMaxFPS ограничивает частоту кадров сверху: движок рисует не чаще fps
// кадров в секунду. Ноль и меньше снимают ограничение.
//
// Это потолок, а не новая целевая частота: выше fps, с которым создан движок
// (New), он не поднимет — движок, созданный на 20 кадров, при SetMaxFPS(60)
// останется на 20. Потолок нужен там, где частота кадров — решение не создателя
// движка, а владельца окна: Window.SetMaxFPS передаёт сюда своё значение.
//
// Можно вызывать в любой момент и с любой горутины; цикл кадров подхватывает
// новое значение на ближайшем тике. Шаг анимаций идёт в том же темпе.
func (e *Engine) SetMaxFPS(fps int) {
	e.lp.SetMaxFPS(fps)
}
