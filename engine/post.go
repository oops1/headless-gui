// post.go — очередь вызовов в горутину кадра.
//
// Движок ведёт отрисовку и обработку ввода в одной горутине, а дерево виджетов
// синхронизации не имеет: менять его из фоновой горутины — гонка с обходом в
// root.Draw. Приложение, у которого данные приходят из сети или из файловой
// системы, обязано как-то попасть обратно в эту горутину, и до сих пор каждое
// заводило для этого свою очередь с диспетчером.
//
// Есть и вторая, менее очевидная причина. window.Run держит горутину
// привязанной к потоку ОС (Win32 требует один поток на окно), и обработчики
// виджетов выполняются именно на ней. Примитивы, которым нужно одинаковое
// состояние блокировки потока при создании и использовании, на этом ломаются:
// заказчик получил падение рантайма «coro: OS thread locking must match
// locking at coroutine creation», создав итератор в обработчике и прочитав его
// из фоновой горутины. Post даёт обратный путь — из фоновой горутины в
// горутину кадра — и позволяет держать такие вещи по одну сторону.
package engine

// Post ставит fn в очередь на выполнение в горутине кадра.
//
// Функции выполняются в порядке постановки, в начале очередного прохода
// цикла кадров — до отрисовки, так что изменения дерева попадают в тот же
// кадр. Из fn можно звать что угодно: движок к этому моменту своих замков не
// держит.
//
// Post безопасен из любой горутины, в том числе из самой горутины кадра: в
// этом случае fn выполнится на СЛЕДУЮЩЕМ проходе, а не сразу. Рекурсия из fn
// поэтому не зацикливает кадр.
//
// Гарантия (GG-68): у запущенного движка функции из Post выполняются на той же
// горутине, что и обработчики ввода, — на горутине цикла кадров — и под
// window.Run, и в webstream. Окно ставит события ОС в эту же очередь, а
// анимации шагает цикл своего движка. Гонки «обработчик против функции из Post»
// поэтому нет, и менять виджеты из fn можно без замков. Потребитель, который
// при запущенном движке сам зовёт Send* со своей горутины, эту гарантию теряет:
// Send* выполняются там, где их позвали, — такой ввод тоже нужно отдавать через
// Post.
//
// Ловушка: без Start() очередь разбирать некому — тогда её разбирают
// RenderOnce и RenderFrameNow, то есть она всё равно опустошается, но в тот
// момент, когда приложение само просит кадр. Движок, который не запущен и
// кадров не рисует, накопленное не выполнит.
func (e *Engine) Post(fn func()) {
	if fn == nil {
		return
	}
	e.postMu.Lock()
	e.posted = append(e.posted, fn)
	e.postMu.Unlock()

	// Будим цикл при ЛЮБОМ темпе — но НЕ инвалидируем: Post сам по себе не
	// повод перерисовывать экран, а вот выполнить работу пора. При внешнем
	// темпе цикл без этого спал бы до запроса кадра, при тикерном — до
	// ближайшего тика; а через Post окно передаёт движку ввод, и нажатие
	// отзывалось бы с задержкой в кадр.
	select {
	case e.wake <- struct{}{}:
	default: // цикл уже разбужен — второго сигнала не нужно
	}
}

// runPosted выполняет накопленные вызовы.
//
// Список забирается целиком и обрабатывается ВНЕ замка: fn вправе позвать
// Post снова (обработчик, который планирует следующий шаг), и держать замок на
// это время значило бы взаимную блокировку. Постановка из fn попадёт в
// следующий проход, а не в текущий, — иначе цикл, планирующий сам себя,
// никогда не дошёл бы до отрисовки.
func (e *Engine) runPosted() {
	e.postMu.Lock()
	queue := e.posted
	e.posted = nil
	e.postMu.Unlock()

	for _, fn := range queue {
		fn()
	}
}

// callOnLoop выполняет fn на горутине движка и ждёт его завершения.
//
// Для вызовов, которые приходят в движок со СВОИХ горутин и трогают дерево
// виджетов: мост доступности зовёт движок из COM и D-Bus. Выполнять такое там
// значило бы завести вторую горутину интерфейса, ровно ту гонку, которую
// снимает очередь (GG-68).
//
// Без запущенного цикла, из самой горутины движка и после Stop fn выполняется
// сразу на вызывающей горутине: ждать некого, а изнутри цикла ждать самого
// себя — значит повиснуть. Если движок остановили, пока вызов стоял в очереди,
// fn не выполнится.
func (e *Engine) callOnLoop(fn func()) {
	if !e.loopRunning() || e.loopGID.Load() == curGoroutineID() {
		fn()
		return
	}
	done := make(chan struct{})
	e.Post(func() {
		defer close(done)
		fn()
	})
	select {
	case <-done:
	case <-e.quit:
	}
}

// flushRounds — сколько проходов очереди делает Flush незапущенного движка:
// функция из очереди вправе поставить в неё следующую, и без предела цепочка,
// планирующая сама себя, не дала бы Flush вернуться.
const flushRounds = 64

// Flush выполняет всё, что стоит в очереди Post, и возвращается, когда очередь
// разобрана.
//
// Нужен тестам приложения: подождать, пока отложенная работа выполнится, не
// рисуя ради этого кадр (RenderOnce на каждое ожидание обходится дорого).
//
//   - Движок не запущен — очередь разбирается здесь же, на вызывающей
//     горутине, повторно, пока функции ставят в неё новые (не больше
//     flushRounds проходов).
//   - Движок запущен — очередь разбирает только цикл кадров, и Flush ждёт,
//     пока он дойдёт до поставленной следом отметки. Работа выполняется на
//     горутине движка, а не на вызывающей.
//
// Из самой горутины движка (обработчик, функция из Post) Flush сразу
// возвращается: ждать завершения очереди, в которой стоишь сам, значит
// повиснуть. После Stop ожидание прерывается.
func (e *Engine) Flush() {
	if !e.started.Load() || e.stopped.Load() {
		for i := 0; i < flushRounds; i++ {
			e.postMu.Lock()
			n := len(e.posted)
			e.postMu.Unlock()
			if n == 0 {
				return
			}
			e.runPosted()
		}
		return
	}
	if e.loopGID.Load() == curGoroutineID() {
		return
	}
	done := make(chan struct{})
	e.Post(func() { close(done) })
	select {
	case <-done:
	case <-e.quit:
	}
}
