// Package minimal — тот же фасад нативного окна, что и window, но без
// возможностей окна (ADR-0013 §3): доступности (UIA, AT-SPI), трея и
// уведомлений, перетаскивания файлов, служб оболочки (открытие ссылок,
// системная тема, языки системы).
//
// Тип Window у обоих фасадов один и тот же (алиас window/core.Window): окна,
// созданные через window и через window/minimal, взаимозаменяемы, и имена
// API совпадают. Переключить программу — сменить путь импорта:
//
//	import window "github.com/oops1/headless-gui/v3/window/minimal"
//
// Без возможности её методы честно отвечают «не поддерживается» так же, как
// на оконной системе, которая её не умеет. Возможность можно подключить и
// поштучно — пустым импортом её пакета platform/* (так делает window).
// Минимальность «заражается»: если любой пакет программы импортирует window,
// возможности подключены для всех окон процесса, — библиотекам поэтому лучше
// импортировать window/minimal, а выбор оставить программе.
//
// Файлы *_gen.go генерирует internal/facadegen:
//
//	go run ./internal/facadegen/cmd/facadegen
