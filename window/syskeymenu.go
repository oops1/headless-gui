package window

// syskeymenu.go — вход в системное меню окна с клавиатуры (Windows).
//
// На отпускании F10 и одиночного Alt DefWindowProc посылает окну
// WM_SYSCOMMAND с SC_KEYMENU и lParam == 0: «войти в меню окна с
// клавиатуры». У окна движка своей строки меню нет — её рисует приложение,
// — но модальный цикл меню всё равно запускался и забирал клавиатуру. Итог:
// приложение получало KeyF10 или KeyAlt, подсвечивало «Файл», а следующая
// стрелка вниз до него уже не доходила.
//
// Глотаем ровно этот вход. Остальные SC_KEYMENU системе нужны: Alt+Space
// приходит с lParam == ' ' и открывает оконное меню (свернуть, переместить,
// закрыть), а Alt+F4 идёт вовсе другим путём (SC_CLOSE).
//
// Файл без платформенного суффикса — правило чистое и проверяется в общем
// прогоне тестов на любой машине.

const (
	// scKeymenu — SC_KEYMENU: вход в меню окна с клавиатуры.
	scKeymenu = 0xF100
	// scMask — младшие четыре бита wParam у WM_SYSCOMMAND система использует
	// сама, и сравнивать команду надо без них (так требует документация).
	scMask = 0xFFF0
)

// swallowKeyboardMenu сообщает, что WM_SYSCOMMAND — вход в меню окна по F10
// или одиночному Alt, который окну движка нужно поглотить.
//
// lParam — символ, с которым вошли в меню: ноль означает F10 или Alt без
// клавиши, пробел — Alt+Space (оконное меню, его оставляем системе), буква —
// поиск мнемоники в строке меню окна (у нас её нет, но и этот путь не
// возникает: WM_SYSCHAR окно и так поглощает).
func swallowKeyboardMenu(wparam, lparam uintptr) bool {
	return wparam&scMask == scKeymenu && lparam == 0
}
