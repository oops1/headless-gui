package window

import (
	"os"
	"runtime/debug"
	"testing"
)

// TestMain разрежает сборки мусора в тестовом бинарнике окна на Windows.
//
// Тесты UI Automation (a11y_*_windows_test.go) передают провайдеру адреса
// переменных стека как uintptr (comCall принимает ...uintptr; ячейки ответов
// вроде `var moved int32` и `uintptr(unsafe.Pointer(&moved))`). Для сборщика
// мусора такой адрес — число, а не указатель: сборка, пришедшаяся между взятием
// адреса и вызовом, может сжать/сдвинуть стек горутины, и провайдер запишет
// ответ по старому адресу («get_DocumentRange: hr=0x0 r=0x0», nil в comCall).
// Раньше сборок в этом бинарнике почти не было: каждый engine.New держал в
// живой куче десятки мегабайт системных шрифтов, и порог следующей сборки
// стоял высоко. Шрифты запасной цепочки теперь грузятся лениво (v3.38), куча
// мала, сборки идут часто — и редкий сбой проявился (при GOGC=5 он
// воспроизводится и на прежнем движке).
//
// Настоящее лечение — ячейки ответов в куче (new(uintptr)) во всех ~90
// местах; до него тестам возвращён прежний темп сборок.
func TestMain(m *testing.M) {
	debug.SetGCPercent(800)
	os.Exit(m.Run())
}
