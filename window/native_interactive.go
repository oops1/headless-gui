package window

// native_interactive.go — необязательные способности нативного окна, которых
// нет у всех бэкендов сразу.
//
// Оконные системы расходятся в том, кто двигает окно. Win32 и X11 позволяют
// клиенту задать позицию (SetPosition), и движок водит окно сам, складывая
// дельты мыши. Wayland позиции не даёт вовсе: клиент просит компоновщик
// «тащи это окно за курсором» или «тяни этот край», и дальше всё делает
// система. Поэтому способность выражена интерфейсом, а не методом
// NativeWindow: бэкенд, который её не реализует, работает как прежде.

// interactiveMover — окно умеет попросить систему переместить себя или
// изменить свой размер, начиная с текущего нажатия кнопки мыши.
type interactiveMover interface {
	// BeginMove просит систему начать перемещение окна.
	//
	// false — бэкенд не умеет или система отказала: вызывающий двигает окно
	// по-старому, через SetPosition.
	BeginMove() bool

	// BeginResize просит систему начать изменение размера за край edges —
	// биты widget.NativeEdgeTop/Bottom/Left/Right.
	BeginResize(edges int) bool
}

// appIDSetter — окно умеет назвать себя среде рабочего стола: по этому
// идентификатору панель задач находит значок и .desktop-файл программы
// (Wayland — xdg_toplevel.app_id, X11 — WM_CLASS).
type appIDSetter interface {
	SetAppID(id string)
}
