package window

// multiwindow.go — несколько окон верхнего уровня в одном процессе.
//
// До этого окно у процесса было одно: Run создавал его и занимал горутину до
// закрытия. Второе окно приходилось делать вторым процессом — так и живёт
// Блокнот WinLine, у которого «окно = процесс». Внутри движка вторичные окна
// давно есть (нативные модалки, оторванные панели докинга), но наружу они не
// показывались и оба — подчинённые: модалка блокирует хозяина, панель
// сворачивается вместе с ним.
//
// Здесь то же самое, но для САМОСТОЯТЕЛЬНОГО окна: своя кнопка в панели
// задач, свой движок, своё дерево виджетов, своя жизнь. Открывается оно
// методом главного окна, а не собственным Run, по одной причине: цикл
// событий у процесса один. На Windows очередь сообщений принадлежит потоку,
// создавшему окно, и окно, созданное из чужой горутины, осталось бы без
// обработки — поэтому создание маршалится на поток главного окна, а его
// насос разбирает сообщения обоих. На X11 и Wayland у второго окна своё
// соединение, и ему заводится собственный насос.

import (
	"fmt"
	"sync"
)

// childWindows — окна, открытые из этого окна.
type childWindows struct {
	mu   sync.Mutex
	list []*Window
}

// OpenWindow показывает ещё одно окно верхнего уровня и сразу возвращает
// управление.
//
// child готовится как обычное окно — своим движком, заголовком, размером,
// SetIcon, SetResizable и прочим, — но Run у него не зовут: цикл событий
// процесса уже крутит это окно. Закрывается child кнопкой ×, своим методом
// Close или вместе с этим окном.
//
// Звать можно откуда угодно, в том числе из обработчика кнопки: создание
// окна ОС маршалится на нужный поток само.
//
// Ошибка возвращается, если это окно ещё не создано (OpenWindow до Run) или
// если окно ОС создать не удалось.
func (win *Window) OpenWindow(child *Window) error {
	if child == nil {
		return fmt.Errorf("window: окно не задано")
	}
	if win.native == nil {
		return fmt.Errorf("window: главное окно ещё не создано — зовите OpenWindow из Run")
	}
	if child.native != nil {
		return fmt.Errorf("window: окно уже открыто")
	}

	// Создание окна ОС — на потоке, которому принадлежит очередь сообщений
	// (Win32). Там, где такого понятия нет, вызов исполняется на месте.
	var err error
	done := make(chan struct{})
	run := func() {
		err = child.bringUp()
		close(done)
	}
	if inv, ok := win.native.(uiThreadInvoker); ok {
		inv.InvokeOnUIThread(run)
	} else {
		run()
	}
	<-done
	if err != nil {
		return err
	}

	// Своё соединение (X11, Wayland) — свой насос событий. На Win32 очередь
	// одна на поток, и сообщения второго окна разбирает насос главного.
	if ep, ok := child.native.(eventPumper); ok {
		ep.StartEventPump()
	}

	win.children.mu.Lock()
	win.children.list = append(win.children.list, child)
	win.children.mu.Unlock()
	return nil
}

// closeChildWindows закрывает окна, открытые из этого, когда оно само
// уходит: без этого их движки и насосы остались бы работать, а окна ОС —
// висеть на экране после закрытия главного.
func (win *Window) closeChildWindows() {
	win.children.mu.Lock()
	list := win.children.list
	win.children.list = nil
	win.children.mu.Unlock()

	for _, child := range list {
		child.shutdown()
	}
}

// shutdown закрывает окно ОС и останавливает его движок.
//
// Нужен отдельно от Close: Close лишь просит окно закрыться (его Run после
// этого сам доберётся до конца), а здесь некому — у второго окна своего Run
// нет.
func (win *Window) shutdown() {
	win.Close()
	win.tearDown()
	if st, ok := win.eng.(interface{ Stop() }); ok {
		st.Stop()
	}
}
