package core

import "github.com/oops1/headless-gui/v3/platform/native"

// hittest.go — какие области окна приложение считает заголовком и кнопками.
//
// Окна движка создаются без рамки: полосу заголовка и кнопки рисует само
// приложение, а система о них не знает. Оттого на Windows 11 не работали две
// привычные вещи. Окно двигалось выставлением позиции из дельт мыши, поэтому
// не прилипало к краям экрана и не раскладывалось по половинам (Aero Snap).
// А наведение на кнопку «развернуть» не показывало макеты привязки (Snap
// Layouts) — система показывает их только над зоной, которую окно объявило
// кнопкой развёртывания.
//
// Сказать об этом можно единственным способом: отвечать системе, что лежит
// под курсором. Приложение знает это точно — оно эти кнопки и нарисовало.

// hitTester — необязательная способность нативного окна: спрашивать у
// приложения, что под курсором.
//
// Бэкенд, который так не умеет (X11, Wayland, macOS), колбэк не получает, и
// окно ведёт себя как прежде — это и требуется: макеты привязки есть только
// у Windows.
type hitTester interface {
	SetHitTest(fn func(x, y int) native.HitArea)
}

// SetHitTest сообщает окну, как узнать, что лежит под точкой: полоса
// заголовка, одна из кнопок управления или обычное содержимое.
//
// Координаты — КЛИЕНТСКИЕ, в логических пикселях, как и всюду в событиях
// мыши. Колбэк зовётся из насоса сообщений ОС, поэтому должен быть быстрым и
// не трогать состояние, которое меняется на горутине движка: достаточно
// сравнить точку с прямоугольниками, посчитанными при раскладке.
//
// nil снимает колбэк, и окно возвращается к прежнему поведению. Бэкенды, где
// этого понятия нет, вызов игнорируют.
func (win *Window) SetHitTest(fn func(x, y int) native.HitArea) *Window {
	win.hitTest = fn
	if win.native != nil {
		win.applyHitTest()
	}
	return win
}

// applyHitTest отдаёт колбэк бэкенду, переводя физические координаты окна в
// логические: бэкенд масштаба не знает, а приложение считает зоны в той же
// сетке, в которой рисует.
func (win *Window) applyHitTest() {
	ht, ok := win.native.(hitTester)
	if !ok {
		return
	}
	fn := win.hitTest
	if fn == nil {
		ht.SetHitTest(nil)
		return
	}
	ht.SetHitTest(func(x, y int) native.HitArea {
		if k := win.scale; k > 0 && k != 1 {
			x = int(float64(x)/k + 0.5)
			y = int(float64(y)/k + 0.5)
		}
		return fn(x, y)
	})
}
