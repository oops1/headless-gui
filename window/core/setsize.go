package core

// setsize.go — программная смена размера окна из приложения (Window.SetSize).
//
// Размер окна приложение могло менять только через Native().SetSize, а там у
// каждого бэкенда своя семантика: на Win32 MoveWindow вызывает WM_SIZE и движок
// перестраивается, на X11 и Wayland размер записывался заранее и до движка не
// доходил — окно оставалось прежним на экране, а форма растягивалась на всю
// его ширину (отчёт RDP-клиента Tandem). Публичный SetSize сводит поведение к
// одному: окно меняет размер и движок проходит тем же путём, что и при ресайзе
// мышью (onResize → холст → раскладка → кадр), ровно один раз на запрос.
//
// Сам путь устроен в бэкендах:
//
//	Win32   MoveWindow → WM_SIZE → onResize сразу; развёрнутому окну
//	        меняется нормальный прямоугольник — размер «после восстановления»;
//	X11     ConfigureWindow → ConfigureNotify от менеджера → onResize; размер
//	        окна меняется только по этому событию (x11_setsize_linux.go);
//	Wayland размер обычного окна выбирает клиент: onResize и буфер нового
//	        размера без ожидания configure (WaylandWindow.SetSize);
//	Cocoa   не реализовано (NSWindow.setFrame в бэкенде не написан).
//
// Развёрнутому, полноэкранному и (Wayland) прилепленному окну размер выбирает
// система: SetSize запоминает заказанный размер, и окно получает его, когда
// вернётся в обычное состояние; пока оно развёрнуто, GetSize отвечает размером
// развёрнутого окна.

// SetSize меняет размер окна. Единицы те же, что у остального API окна
// (SetMinSize, SetInitialBounds): ЛОГИЧЕСКИЕ пиксели, окно умножает их на
// масштаб интерфейса. Окно в режиме ContentFitMode FitScale логического
// размера не имеет (холст — дизайн-размер, масштаб подгоняется под окно): там
// размер задаётся в пикселях окна.
//
// Размер окна уже такой — ничего не происходит. Иначе окно меняется, и движок
// получает новый размер по обычному пути ресайза ровно один раз: холст и
// раскладка перестраиваются, кадр рисуется заново. Если система поправила
// размер (минимум, шаг, рамка), движок получит фактический: приложению
// достаточно перечитать Native().GetSize() (физические пиксели) после
// того, как окно успело ответить — на X11 ответ менеджера приходит позже самого
// вызова, на Win32 и Wayland — сразу.
//
// Вызов до Run() задаёт начальный размер окна (как SetInitialBounds без
// положения); последний вызов перекрывает предыдущие и размер из SetInitialBounds.
// width или height не больше нуля игнорируются. Безопасно звать из любой
// горутины.
func (win *Window) SetSize(width, height int) {
	if width <= 0 || height <= 0 {
		return
	}
	if win.native == nil {
		win.initial.sizeSet = true
		win.initial.w, win.initial.h = width, height
		return
	}
	pw, ph := width, height
	if win.fitMode != FitScale && win.scale > 0 && win.scale != 1 {
		pw = int(float64(width)*win.scale + 0.5)
		ph = int(float64(height)*win.scale + 0.5)
	}
	// Окно ОС меняется на потоке своего цикла сообщений (Win32 привязывает
	// окно к потоку); бэкенды без маршалинга получают вызов сразу.
	win.onNative(func() {
		if win.native == nil {
			return
		}
		if cw, ch := win.native.GetSize(); cw == pw && ch == ph {
			return
		}
		win.native.SetSize(pw, ph)
	})
}
