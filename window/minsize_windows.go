//go:build windows

package window

// defaultMinTrackW/H — минимальный размер окна, который Win32 отдаёт в
// WM_GETMINMAXINFO, когда приложение не задало свой: столько нужно обычному
// окну приложения, чтобы в заголовке помещались кнопки управления.
const (
	defaultMinTrackW = 320
	defaultMinTrackH = 240
)

// fitMinTrack возвращает минимальный размер окна для WM_GETMINMAXINFO с
// поправкой на запрошенный размер окна.
//
// Windows применяет ptMinTrackSize не только к пользовательскому ресайзу, но
// и к созданию окна: окно, запрошенное меньше минимума, молча вырастает до
// него. Кадр при этом остаётся прежнего размера, и разница остаётся
// непрокрашенной — именно так окно модалки с диалогом 420×168 создавалось
// высотой 240, а лишние 72 пикселя выглядели «продолжением рамки диалога»
// с пустотой внутри.
//
// Поэтому для окна меньше дефолта минимум опускается до его размера. Явно
// заданный SetMinSize (minW/minH > 0) не трогаем — это осознанное решение
// приложения.
func fitMinTrack(minW, minH, width, height int) (int, int) {
	if minW == 0 && width > 0 && width < defaultMinTrackW {
		minW = width
	}
	if minH == 0 && height > 0 && height < defaultMinTrackH {
		minH = height
	}
	return minW, minH
}
