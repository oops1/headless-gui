//go:build linux && !android

package window

// x11_dpi_linux.go — HiDPI на X11: масштаб интерфейса из настроек рабочего
// стола.
//
// На Windows движок давно спрашивает масштаб у системы, на Linux — нет:
// DetectScale там не было вовсе, и на мониторе 4K интерфейс выходил вдвое
// мельче положенного. Единственный способ сказать движку правду состоял в
// переменной HEADLESS_GUI_SCALE, то есть человек должен был знать о ней и
// выставлять руками.
//
// В X11 общесистемного «масштаба» нет; то, что им пользуются все тулкиты, —
// это ресурс Xft.dpi в базе ресурсов X-сервера (свойство RESOURCE_MANAGER
// корневого окна). Его выставляют GNOME, KDE и startx-скрипты, по нему
// считают размер шрифта GTK и Qt. 96 точек на дюйм — масштаб 1.

// atomResourceManager — предопределённый атом RESOURCE_MANAGER (X11/Xatom.h).
// Интернировать его не нужно: номер зафиксирован протоколом.
const atomResourceManager = 23

// DetectScale возвращает масштаб интерфейса по настройкам рабочего стола.
// 0 — узнать не удалось: тогда окно остаётся при масштабе 1, как было.
//
// Реализует scaleDetector: окно спрашивает его до создания окна ОС, поэтому
// соединение при необходимости открывается здесь же — повторный connect при
// Create им же и воспользуется.
func (w *X11Window) DetectScale() float64 {
	if err := w.connect(); err != nil {
		return 0
	}
	_, _, data := w.x11GetProperty(w.rootWin, atomResourceManager, false)
	if k, ok := xftScaleFromResources(string(data)); ok {
		return k
	}
	// Запасной путь: GDK_SCALE задают там, где базы ресурсов нет вовсе
	// (голый startx, кадровый буфер). Значение целое — так его и трактуем.
	if v := envGDKScale(); v > 0 {
		return v
	}
	return 0
}
