package output

// slab.go — переиспользуемые буферы данных тайлов (v3.38).
//
// Кадр, в котором изменилось всё окно (панорамирование картинки в 4K),
// несёт 33 МБ пикселей, и до сих пор их выделяли заново на каждый кадр:
// обнуление свежей памяти и сборка мусора стоили заметной доли кадра.
// Движок умеет класть данные тайлов в буферы из пула и принимать их назад,
// но только по явному возврату — Frame.Release: кадр уходит потребителю по
// каналу, и вправе ли тот ещё читать Data, знает только он сам.
//
// Контракт жизни Data:
//
//   - по умолчанию (Engine.SetFrameRecycling(false), так было всегда) Data
//     принадлежит потребителю навсегда: его можно хранить сколько угодно;
//   - при включённой переработке Data действительна до Frame.Release; кто
//     Release не зовёт, ничего не теряет — буфер просто достанется сборщику
//     мусора, как раньше;
//   - после Release кадр читать нельзя: его байты вскоре перезапишет
//     следующий кадр.

import (
	"sync"
	"sync/atomic"
)

const (
	// slabSmall — граница двух классов пула: кадры с парой изменившихся
	// тайлов не должны вытеснять из пула крупные буферы и наоборот.
	slabSmall = 1 << 20
	// slabGranule — шаг округления ёмкости крупных буферов: воркеры одного
	// кадра просят почти одинаково много, и округление даёт им взаимно
	// подходящие буферы.
	slabGranule = 256 << 10
	// slabMaxPooled — больше этого в пул не кладём (редкие гигантские кадры
	// не должны залёживаться в памяти).
	slabMaxPooled = 128 << 20
)

var slabPools [2]sync.Pool

// Slab — буфер данных тайлов кадра, берётся из пула (GetSlab) и возвращается
// туда через Frame.Release.
type Slab struct {
	buf []byte
	// retired: 1 — буфер возвращён в пул или закреплён (Pin) и в пул не
	// вернётся; второй Release по копии кадра ничего не делает.
	retired atomic.Uint32
}

// GetSlab возвращает буфер длины 0 и ёмкости не меньше n. Содержимое ёмкости
// не обнулено: вызывающий обязан записать каждый байт, который отдаст.
func GetSlab(n int) *Slab {
	cls := 0
	if n > slabSmall {
		cls = 1
	}
	if v := slabPools[cls].Get(); v != nil {
		s := v.(*Slab)
		if cap(s.buf) >= n {
			s.buf = s.buf[:0]
			s.retired.Store(0)
			return s
		}
		slabPools[cls].Put(s) // мал для этого кадра — оставляем другим
	}
	c := n
	if cls == 1 {
		c = (n + slabGranule - 1) / slabGranule * slabGranule
	}
	return &Slab{buf: make([]byte, 0, c)}
}

// Bytes — буфер длины 0 с полной ёмкостью; в него дописывают (append в пределах
// ёмкости не копирует). Срезы Data тайлов — трёхиндексные, в этот же массив.
func (s *Slab) Bytes() []byte { return s.buf[:0] }

// Pin навсегда снимает буфер с переработки: Release для него — пустой вызов.
func (s *Slab) Pin() { s.retired.Store(1) }

// release возвращает буфер в пул (один раз).
func (s *Slab) release() {
	if !s.retired.CompareAndSwap(0, 1) {
		return
	}
	if cap(s.buf) > slabMaxPooled {
		return
	}
	cls := 0
	if cap(s.buf) > slabSmall {
		cls = 1
	}
	slabPools[cls].Put(s)
}

// AttachSlabs привязывает к кадру буферы, в которых лежат Data его тайлов
// (вызывает движок при сборке кадра).
func (f *Frame) AttachSlabs(s ...*Slab) { f.slabs = append(f.slabs, s...) }

// Pin закрепляет буферы кадра за потребителем навсегда: Release перестаёт
// возвращать их в пул. Движок зовёт это для кадров, которые видит синхронный
// сток (FrameSink) — что тот сделает с Data, движку неизвестно.
func (f Frame) Pin() {
	for _, s := range f.slabs {
		s.Pin()
	}
}

// Release сообщает движку, что потребитель закончил с кадром: данные его
// тайлов (DirtyTile.Data) вернутся в пул и будут перезаписаны следующими
// кадрами. После вызова Data читать нельзя.
//
// Безопасен всегда: у кадра, собранного не движком, или при выключенной
// переработке (Engine.SetFrameRecycling) это пустой вызов; повторный вызов
// (в том числе по копии кадра) тоже ничего не делает. Не звать Release
// допустимо — буфер тогда соберёт сборщик мусора.
func (f Frame) Release() {
	for _, s := range f.slabs {
		s.release()
	}
}
