// move.go — переехавшее содержимое кадра.
//
// Перетаскивание окна и прокрутка не меняют пиксели — они переносят их с
// места на место. Отправлять их заново значит платить за то, что у
// потребителя уже есть: в RDP этому соответствует пара команд через кэш
// поверхности (четырнадцать байт вместо сотни килобайт), локально — обычный
// блит внутри буфера.
package output

import "image"

// MoveRegion — прямоугольник, содержимое которого переехало без изменений.
//
// From — откуда взять, Rect — куда положить. Размер задаётся Rect: область
// источника того же размера, иначе это уже не перенос, а масштабирование.
type MoveRegion struct {
	From image.Point
	Rect image.Rectangle
}

// Src возвращает прямоугольник источника.
func (m MoveRegion) Src() image.Rectangle {
	return image.Rect(m.From.X, m.From.Y, m.From.X+m.Rect.Dx(), m.From.Y+m.Rect.Dy())
}

// Empty сообщает, что переносить нечего.
func (m MoveRegion) Empty() bool { return m.Rect.Empty() }
