// region.go — чем нарисована область кадра.
//
// Наружу из движка уходили только пиксели, и потребитель восстанавливал по
// ним то, что движку было известно с самого начала. В WinLine это стоило
// дорого: на каждой области, где кодек без потерь не дал двукратного
// сжатия, целиком считался второй кодек — с потерями, — и результаты
// сравнивались по размеру. Весь классификатор содержимого сводился к
// константе «ужалось вдвое».
//
// Между тем ответ известен на входе и стоит одного присваивания в уже
// существующих циклах отрисовки. Он же открывает быстрые пути: область
// сплошного цвета передаётся протокольной командой заливки и не кодируется
// вовсе — а для рабочего стола это обои, панель, рамки окон, фоны.
package output

import (
	"image"
	"image/color"
)

// RegionKind — чем залита область.
type RegionKind uint8

const (
	// RegionMixed — неизвестно либо смешано. Честное «не знаю»: потребитель
	// поступает с такой областью как раньше. Замысел не в том, чтобы
	// классифицировать всё.
	RegionMixed RegionKind = iota
	// RegionSolid — сплошная заливка одним цветом (Region.Color).
	RegionSolid
	// RegionImage — блит изображения.
	RegionImage
	// RegionText — глифы.
	RegionText
	// RegionVideo — тайл целиком лежит в видимой части окна программы,
	// показывающего видео (Region.VideoID, Frame.Videos). Добавлено в v4.0:
	// потребитель, не знающий этого вида, поступает с ним как с RegionMixed.
	RegionVideo
)

// String — имя вида для диагностики и тестов.
func (k RegionKind) String() string {
	switch k {
	case RegionSolid:
		return "solid"
	case RegionImage:
		return "image"
	case RegionText:
		return "text"
	case RegionVideo:
		return "video"
	default:
		return "mixed"
	}
}

// Region — область кадра и то, чем она нарисована.
//
// Прямоугольник совпадает с тайлом: классификация ведётся по тайлам, и
// область — это тот же тайл, только с признаком.
type Region struct {
	Rect  image.Rectangle
	Kind  RegionKind
	// Color осмыслен только при Kind == RegionSolid.
	//
	// Порядок каналов — тот же, что у DirtyTile.Data, то есть выбранный
	// Engine.SetPixelFormat: при FormatBGRX здесь лежат переставленные
	// каналы. Это байты буфера, а не портируемый цвет — читающий их как
	// обычный RGBA получит неверный оттенок ровно тогда, когда сам просил
	// другой формат.
	Color color.RGBA
	// VideoID — номер окна программы (output.VideoRegion.ID) при Kind ==
	// RegionVideo; ноль в остальных случаях. Отдельным полем, а не в Color:
	// Color — байты буфера, и номер в них читался бы как оттенок.
	VideoID uint32
}

// VideoRegion — окно программы, показывающее видео, в этом кадре — даже если
// в этом кадре оно не обновлялось: потребителю видеокодека нужен весь список
// фильмов на экране.
type VideoRegion struct {
	// ID — стабильный номер окна (тот же, что в Region.VideoID).
	ID uint32
	// Rect — где окно на экране, физические пиксели, обрезано холстом.
	Rect image.Rectangle
	// Cover — что лежит над окном: окна выше по Z, панель задач, открытые
	// меню, затемнение модального окна. Физические пиксели, обрезано Rect.
	// Полупрозрачное тоже закрывает: кодек видео его не нарисует.
	Cover []image.Rectangle
}
