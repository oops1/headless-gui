// region.go — чем нарисована область кадра.
//
// Наружу из движка уходили только пиксели, и потребитель восстанавливал по
// ним то, что движку было известно с самого начала. В WinLine это стоило
// дорого: на каждой области, где кодек без потерь не дал двукратного
// сжатия, целиком считался второй кодек — с потерями, — и результаты
// сравнивались по размеру. Весь классификатор содержимого сводился к
// константе «ужалось вдвое».
//
// Между тем ответ известен на входе и стоит одного присваивания в уже
// существующих циклах отрисовки. Он же открывает быстрые пути: область
// сплошного цвета передаётся протокольной командой заливки и не кодируется
// вовсе — а для рабочего стола это обои, панель, рамки окон, фоны.
package output

import (
	"image"
	"image/color"
)

// RegionKind — чем залита область.
type RegionKind uint8

const (
	// RegionMixed — неизвестно либо смешано. Честное «не знаю»: потребитель
	// поступает с такой областью как раньше. Замысел не в том, чтобы
	// классифицировать всё.
	RegionMixed RegionKind = iota
	// RegionSolid — сплошная заливка одним цветом (Region.Color).
	RegionSolid
	// RegionImage — блит изображения.
	RegionImage
	// RegionText — глифы.
	RegionText
)

// String — имя вида для диагностики и тестов.
func (k RegionKind) String() string {
	switch k {
	case RegionSolid:
		return "solid"
	case RegionImage:
		return "image"
	case RegionText:
		return "text"
	default:
		return "mixed"
	}
}

// Region — область кадра и то, чем она нарисована.
//
// Прямоугольник совпадает с тайлом: классификация ведётся по тайлам, и
// область — это тот же тайл, только с признаком.
type Region struct {
	Rect  image.Rectangle
	Kind  RegionKind
	Color color.RGBA // осмыслен только при Kind == RegionSolid
}
