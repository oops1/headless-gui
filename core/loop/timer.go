// timer.go — отложенные и повторяющиеся вызовы на горутине движка.
//
// До сих пор у приложения был Post и больше ничего: чтобы выполнить что-то
// через полсекунды или раз в минуту, каждое место заводило time.AfterFunc и
// из него звало Post. Выходило две беды. Первая — остановка: таймер надо
// отменить при закрытии окна, и часть кода этого не делала, так что после
// выхода жили горутины и будили мёртвый движок. Вторая — повторение:
// time.Ticker шлёт тик, не дожидаясь обработчика, и медленный обработчик
// копил в очереди Post вызовы, которые потом выполнялись разом.
//
// Здесь обе беды закрыты в движке: таймер принадлежит движку, исполняется на
// его горутине и гаснет вместе с ним.

package loop

import (
	"sync"
	"time"
)

// minEvery — наименьший период Every. Нулевой или отрицательный период
// превратил бы повтор в бесконечную цепочку вызовов без пауз: следующий запуск
// ставится сразу после предыдущего, и цикл кадров не дошёл бы до отрисовки.
const minEvery = time.Millisecond

// Timer — ручка отложенного или повторяющегося вызова, созданного After или
// Every. Все методы безопасны из любой горутины.
type Timer struct {
	l     *Loop
	fn    func()
	every time.Duration // 0 — разовый вызов

	mu      sync.Mutex
	tm      *time.Timer // ожидающий системный таймер; nil, пока ничего не заведено
	stopped bool        // больше не сработает (отменён, выполнен или движок остановлен)
}

// After выполняет fn на горутине движка через d и возвращает ручку, которой
// вызов можно отменить.
//
// fn исполняется тем же путём, что и Post: на горутине цикла кадров, перед
// отрисовкой очередного кадра, без замков движка. Дерево виджетов принадлежит
// движку, и трогать его из горутины системного таймера значило бы гонку с
// обходом в root.Draw — поэтому таймер лишь ставит вызов в очередь, а сам
// вызов делает движок.
//
// Пока таймер ждёт, он не держит горутин: системный таймер просыпается один раз
// и сразу отдаёт работу движку. Отмена после срабатывания, но до выполнения
// тоже работает — fn, уже стоящий в очереди, проверяет флаг и не выполняется.
//
// Если движок уже остановлен или fn пуст, возвращается уже остановленный
// таймер: ничего не заводится. Остановка движка гасит все его таймеры.
// d <= 0 даёт вызов на ближайшем проходе цикла, как Post.
//
// Ловушка та же, что у Post: без Start() очередь разбирают лишь RenderOnce,
// RenderFrameNow и Flush, поэтому у незапущенного движка fn выполнится в тот
// момент, когда приложение само попросит кадр.
func (l *Loop) After(d time.Duration, fn func()) *Timer {
	return l.newTimer(d, 0, fn)
}

// Every повторяет fn на горутине движка каждые d, пока таймер не остановят
// или не остановят движок.
//
// Следующий запуск планируется ПОСЛЕ того, как fn вернулся, то есть между
// концом одного вызова и началом следующего проходит d. Так медленный
// обработчик замедляет повтор, а не копит очередь: time.Ticker слал бы тики
// независимо от обработчика, и после долгой паузы вызовы шли бы подряд, один
// за другим. Цена — период дрейфует на время работы fn; для автосохранения и
// повтора поиска это то, что нужно.
//
// fn может остановить собственный таймер: после возврата следующий запуск не
// планируется. Период меньше миллисекунды округляется вверх до миллисекунды.
// Остальное — как у After.
func (l *Loop) Every(d time.Duration, fn func()) *Timer {
	if d < minEvery {
		d = minEvery
	}
	return l.newTimer(d, d, fn)
}

// newTimer заводит таймер и записывает его в реестр движка.
func (l *Loop) newTimer(first, every time.Duration, fn func()) *Timer {
	t := &Timer{l: l, fn: fn, every: every}
	if fn == nil {
		t.stopped = true
		return t
	}

	// Проверка stopped и запись в реестр идут под одним замком, а Stop движка
	// сначала выставляет stopped и лишь потом обходит реестр под тем же замком.
	// Поэтому таймер, созданный одновременно со Stop, либо видит остановку и не
	// заводится, либо попадает в реестр до обхода и будет погашен. Без этого
	// оставалась щель, в которой таймер переживал движок.
	l.timersMu.Lock()
	if l.stopped.Load() {
		l.timersMu.Unlock()
		t.stopped = true
		return t
	}
	if l.timers == nil {
		l.timers = make(map[*Timer]struct{})
	}
	l.timers[t] = struct{}{}
	l.timersMu.Unlock()

	t.arm(first)
	return t
}

// Stop отменяет таймер: после возврата fn не будет вызван заново, а уже
// поставленный в очередь вызов не выполнится. Вызов, который к этому моменту
// уже выполняется на горутине движка, Stop не прерывает и не ждёт — ждать его
// из обработчика значило бы повиснуть на самом себе.
//
// Безопасен из любой горутины, в том числе из самого fn, и повторно.
func (t *Timer) Stop() {
	t.mu.Lock()
	t.stopLocked()
	t.mu.Unlock()
	t.l.forgetTimer(t)
}

// Stopped сообщает, что таймер больше не сработает: его остановили, остановили
// движок или это разовый вызов, который уже начал выполняться.
func (t *Timer) Stopped() bool {
	t.mu.Lock()
	defer t.mu.Unlock()
	return t.stopped
}

// stopLocked помечает таймер остановленным и гасит ожидающий системный таймер.
// Вызывать под t.mu.
func (t *Timer) stopLocked() {
	t.stopped = true
	if t.tm != nil {
		t.tm.Stop()
		t.tm = nil
	}
}

// arm заводит системный таймер на d, если таймер ещё жив. Проверка и заведение
// идут под одним замком с Stop: повтор, который перепланирует себя на
// горутине движка одновременно с остановкой, иначе мог бы завести таймер уже
// после Stop, и тот пережил бы и ручку, и движок.
func (t *Timer) arm(d time.Duration) {
	t.mu.Lock()
	defer t.mu.Unlock()
	if t.stopped {
		return
	}
	// Сам системный таймер не исполняет fn: его обратный вызов идёт на
	// служебной горутине рантайма, где дерево виджетов трогать нельзя. Он
	// только передаёт работу движку.
	t.tm = time.AfterFunc(d, func() { t.l.Post(t.fire) })
}

// fire выполняется на горутине движка (из очереди Post).
func (t *Timer) fire() {
	t.mu.Lock()
	if t.stopped {
		// Отменили после срабатывания, но до того, как очередь дошла сюда.
		t.mu.Unlock()
		return
	}
	t.tm = nil
	if t.every == 0 {
		// Разовый вызов: помечаем выполненным до fn, чтобы Stop изнутри fn и
		// снаружи был пустой операцией, а реестр не копил мёртвые таймеры.
		t.stopped = true
	}
	t.mu.Unlock()

	// Граница таймера (failure.go): упавший fn не мешает ни очереди, ни
	// следующему срабатыванию Every.
	if t.every == 0 {
		t.l.forgetTimer(t)
		t.l.host.GuardCall("Timer", t.fn)
		return
	}

	t.l.host.GuardCall("Timer", t.fn)
	// Следующий запуск — только после fn (см. Every). Если fn остановил таймер
	// или движок остановили, arm это увидит и ничего не заведёт.
	t.arm(t.every)
}

// forgetTimer убирает таймер из реестра движка.
func (l *Loop) forgetTimer(t *Timer) {
	l.timersMu.Lock()
	delete(l.timers, t)
	l.timersMu.Unlock()
}

// stopTimers гасит все таймеры движка; зовётся из Stop после того, как stopped
// выставлен. Таймеры останавливаются ВНЕ замка реестра: Timer.Stop сам берёт
// замок реестра, и держать его здесь значило бы взаимную блокировку.
func (l *Loop) stopTimers() {
	l.timersMu.Lock()
	all := make([]*Timer, 0, len(l.timers))
	for t := range l.timers {
		all = append(all, t)
	}
	l.timers = nil
	l.timersMu.Unlock()

	for _, t := range all {
		t.mu.Lock()
		t.stopLocked()
		t.mu.Unlock()
	}
}
