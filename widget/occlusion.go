// occlusion.go — не рисовать то, что всё равно закроют.
//
// Движок рисует снизу вверх и не спрашивает, видно ли то, что он рисует.
// Окно под другим окном отрисовывается целиком, а потом закрашивается; при
// десятке перекрывающихся окон это кратные затраты на каждый полный кадр.
//
// Здесь виджет получает право сказать, что он закрывает собой: обход идёт
// сверху вниз, копит закрытую площадь и пропускает поддеревья, целиком в неё
// попавшие.
//
// Точность важнее агрессивности. Ошибка «нарисовали лишнее» видна только в
// профиле; ошибка в другую сторону — дыра на экране. Поэтому:
//
//   - виджет, ничего не объявивший, считается ПРОЗРАЧНЫМ;
//   - объявлять надо площадь, которая закрашивается ПОЛНОСТЬЮ и непрозрачно:
//     скруглённое окно — без своих углов, стеклянная панель — ничего вовсе,
//     мягкая тень не закрывает даже собственный прямоугольник;
//   - проверка вложенности — в ОДИН объявленный прямоугольник, а не в их
//     объединение: поддерево, закрытое двумя окнами вскладчину, будет
//     нарисовано зря, зато никакая хитрая форма объединения не даст ошибиться.
package widget

import "image"

// OpaqueRegioner — виджет, объявляющий, какую площадь он закрывает
// непрозрачно. Координаты АБСОЛЮТНЫЕ логические, как у Bounds.
//
// Реализовывать необязательно: виджет без этого метода считается прозрачным
// и ничего под собой не скрывает.
type OpaqueRegioner interface {
	OpaqueRegion() []image.Rectangle
}

// maxOccluders — сколько закрывающих прямоугольников копит обход одного
// уровня.
//
// Список короткий намеренно: проверка идёт линейно на каждого ребёнка, а
// толку от сотого окна нет — на экране, где столько окон, верхние и так
// закрывают всё. Переполнение не даёт ошибки, только теряет часть экономии.
const maxOccluders = 16

// occluders — закрытая площадь, накопленная обходом сверху вниз.
//
// Массив, а не срез: копилка живёт ровно один проход по детям одного
// контейнера, и растущий срез означал бы аллокацию на каждый контейнер
// каждого кадра — ради экономии, которая как раз и меряется в аллокациях.
type occluders struct {
	rects [maxOccluders]image.Rectangle
	n     int
}

// add запоминает площадь, которую закрывает виджет w, если он её объявил.
func (o *occluders) add(w Widget) {
	if o.n >= maxOccluders {
		return
	}
	r, ok := w.(OpaqueRegioner)
	if !ok {
		return
	}
	for _, rect := range r.OpaqueRegion() {
		if rect.Empty() {
			continue
		}
		o.rects[o.n] = rect
		o.n++
		if o.n >= maxOccluders {
			return
		}
	}
}

// covers сообщает, лежит ли r целиком внутри одного из накопленных
// прямоугольников.
func (o *occluders) covers(r image.Rectangle) bool {
	if r.Empty() {
		return false
	}
	for _, c := range o.rects[:o.n] {
		if r.In(c) {
			return true
		}
	}
	return false
}

// Occluded сообщает, закрыт ли виджет целиком тем, что нарисуют поверх него.
//
// Считается по прямоугольнику ПОДДЕРЕВА (SubtreeRect): виджет мог быть узким,
// а его дети — вылезать наружу, и закрывать надо всё, что поддерево рисует.
// Пустое поддерево не пропускается: пустой прямоугольник означает «не знаю,
// где это», а не «нигде».
func (o *occluders) Occluded(w Widget) bool {
	if o.n == 0 {
		return false
	}
	// Оверлей рисуется отдельным проходом, и его площадь в границы виджета не
	// входит — пропустить такой виджет значит потерять открытое меню.
	if od, ok := w.(OverlayDrawer); ok && od.HasOverlay() {
		return false
	}
	return o.covers(SubtreeRect(w))
}

// oneRegion отдаёт одноэлементный список, не выделяя памяти под него.
//
// Буфер принадлежит виджету и живёт между кадрами: OpaqueRegion зовут на
// каждый кадр для каждого рисуемого виджета, и свежий срез там — аллокация
// ровно в том месте, экономию которого мы и меряем. Отдать срез по буферу
// безопасно: обход читает его тут же и не держит.
func oneRegion(buf *[1]image.Rectangle, r image.Rectangle) []image.Rectangle {
	if r.Empty() {
		return nil
	}
	buf[0] = r
	return buf[:]
}

// opaqueRect возвращает площадь, которую сплошная заливка прямоугольника b
// со скруглением cr закрывает НАВЕРНЯКА.
//
// Скруглённый прямоугольник не накрывает своих углов, зато на любой строке
// между верхним и нижним скруглением он тянется во всю ширину. Эту полосу и
// объявляем — она и есть та часть, за которую можно ручаться. Отрезать по cr
// со всех четырёх сторон было бы вернее математически и хуже по делу: у окна
// 720×440 со скруглением 8 полоса теряет 3%, а квадрат — 4%.
func opaqueRect(b image.Rectangle, cr int) image.Rectangle {
	if b.Empty() {
		return image.Rectangle{}
	}
	if cr <= 0 {
		return b
	}
	// Скругление, не помещающееся в фигуру, — не полоса, а что-то ближе к
	// кругу: ручаться за прямоугольник в ней нельзя. Проверять ОБА размера
	// обязательно: image.Rect при перевёрнутых координатах не отдаёт пустой
	// прямоугольник, а переставляет их местами — и вместо «ничего не
	// закрываю» вышло бы «закрываю вот эту чужую полосу».
	if 2*cr >= b.Dy() || 2*cr > b.Dx() {
		return image.Rectangle{}
	}
	return image.Rect(b.Min.X, b.Min.Y+cr, b.Max.X, b.Max.Y-cr)
}
