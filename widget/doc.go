// Package widget содержит интерфейсы и реализации UI-виджетов.
//
// С версии 4.0 пакет — фасад (ADR-0012): код живёт в widget/base и
// подпакетах (widget/xaml, widget/text…), а здесь для каждого их
// экспортированного имени — алиас типа, обёртка функции с той же
// документацией, константа и переменная. Алиас — тот же тип: методы,
// встраивание (struct{ widget.Base }), утверждения типов и удовлетворение
// интерфейсов прежние, программы импортируют widget, как раньше. Переменные
// фасада (ошибки Err*, кривые Ease*) — копии значений: errors.Is и вызовы
// кривых работают, а присваивание widget.EaseOutCubic = f меняет только
// копию фасада. Имена типов в рефлексии и трассах — по пакету, где тип
// живёт: base.Button, text.TextInput.
//
// Своего кода у фасада немного: JSON-загрузчик (loader.go, тип UINode) — он
// строит виджеты всех пакетов — и регистрация XAML-тегов пакетов виджетов
// при первой загрузке разметки (xaml_register.go).
//
// Файлы *_gen.go генерирует internal/facadegen:
//
//	go run ./internal/facadegen/cmd/facadegen
//
// Тест фасада (facade_test.go) падает, если фасад не совпадает с выводом
// генератора или в нём не хватает имён.
