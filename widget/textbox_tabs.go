package widget

import "strings"

// textbox_tabs.go — табстопы многострочного редактора.
//
// Символ табуляции шрифт рисует как «ничего» или как коробку нулевой/случайной
// ширины, и код с отступами в редакторе превращался в кашу: вложенные блоки
// стояли вплотную друг к другу. Табуляция должна выравнивать текст по сетке,
// кратной ширине N пробелов, — как это делает любой редактор кода. Логика
// вынесена сюда чистыми функциями: она нужна и раскладке (ширина строки,
// положение каретки), и отрисовке, и обе обязаны считать одинаково, иначе
// каретка поедет относительно букв.

// tbDefaultTabSize — ширина табуляции в пробелах, когда включён приём Tab
// (AcceptTab), а TabSize не задан: так принято в большинстве редакторов.
const tbDefaultTabSize = 4

// tabStopAfter — x ближайшего табстопа СТРОГО правее x. Строго: табуляция,
// стоящая ровно на границе сетки, всё равно сдвигает текст на целую ячейку,
// иначе ряд подряд идущих табуляций «слипался» бы после первой.
func tabStopAfter(x, tabW int) int {
	if tabW <= 0 {
		return x
	}
	return (x/tabW + 1) * tabW
}

// measureTabbed — ширина строки text, начинающейся с x=0, с учётом табстопов.
// measure измеряет кусок БЕЗ табуляций (шрифтом виджета).
//
// Кусок между табуляциями меряется отдельно, а не вычитанием из ширины целого:
// измеритель отдаёт целые пиксели и не аддитивен, так что ширина префикса,
// посчитанная двумя способами, расходилась бы на пиксель, и каретка уезжала от
// выделения. Один и тот же способ везде — единственная гарантия совпадения.
//
// tabW <= 0 — табстопов нет, как до их появления: строка меряется целиком.
func measureTabbed(text string, tabW int, measure func(string) int) int {
	if tabW <= 0 || strings.IndexByte(text, '\t') < 0 {
		return measure(text)
	}
	x := 0
	for {
		i := strings.IndexByte(text, '\t')
		if i < 0 {
			return x + measure(text)
		}
		if i > 0 {
			x += measure(text[:i])
		}
		x = tabStopAfter(x, tabW)
		text = text[i+1:]
	}
}

// tabRun — непрерывный отрезок строки без табуляций: полуинтервал рун [From, To).
type tabRun struct{ From, To int }

// splitTabRuns режет руны [from, to) строки rs на отрезки между табуляциями.
// Сами табуляции и пустые отрезки в результат не входят: рисовать в них нечего,
// а их ширину даёт сдвиг к следующему отрезку.
func splitTabRuns(rs []rune, from, to int) []tabRun {
	var out []tabRun
	start := from
	for i := from; i <= to; i++ {
		if i < to && rs[i] != '\t' {
			continue
		}
		if i > start {
			out = append(out, tabRun{start, i})
		}
		start = i + 1
	}
	return out
}
