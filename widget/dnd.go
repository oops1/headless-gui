package widget

// FileDropTarget — опциональный интерфейс виджета, принимающего файлы,
// перетащенные из ОС (проводник / файловый менеджер) в окно приложения.
//
// Движок доставляет событие через engine.SendFilesDropped: событие всплывает
// от самого глубокого виджета под точкой сброса к корню (bubbling, как у
// колеса мыши). Первый виджет, вернувший true, поглощает событие и
// останавливает всплытие.
//
//	x, y  — ЛОГИЧЕСКИЕ координаты точки сброса в пространстве холста
//	paths — абсолютные пути к сброшенным файлам
//
// Возврат: true — событие обработано (всплытие прекращается); false — передать
// родителю.
type FileDropTarget interface {
	OnFilesDropped(x, y int, paths []string) bool
}
