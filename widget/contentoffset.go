package widget

// contentoffset.go — координаты детей контейнера, который показывает их со
// сдвигом (ScrollView).
//
// ДВЕ СИСТЕМЫ КООРДИНАТ. Экран — то, что видит человек и что знают движок,
// окно и система. Кадр ребёнка прокрутки — координаты его Bounds(): они лежат
// в «содержимом» и от прокрутки не меняются. Точка экрана p соответствует точке
// кадра p+off, где off — сумма ContentOffset всех контейнеров над виджетом.
//
// ПОЧЕМУ НЕ СДВИГАТЬ BOUNDS. Прежде всего этого не позволил PERF-12 (см.
// ScrollView.Draw): SetBounds на каждом кадре будил инвалидацию вхолостую и
// давал гонку с событиями. Но и сам по себе сдвиг ломает больше, чем чинит:
// приложение, раскладывающее детей по содержимому, читает и пишет Bounds в одной
// системе координат; Panel и Canvas держат внуков в абсолютных координатах, и
// SetBounds родителя их не двигает, так что при каждом шаге прокрутки пришлось
// бы обойти и перекладывать всё поддерево (на длинном списке — тысячи вызовов
// на колесо мыши).
//
// Поэтому дети остаются в своей системе координат, а на границах с внешним
// миром координаты переводятся — ровно в одном месте на каждый вид границы:
//
//   - события мыши и хит-тест — движок (engine/frames.go): по пути вниз он
//     прибавляет ContentOffset каждого контейнера, и ребёнок получает точку в
//     своих координатах;
//   - области перерисовки, которые ребёнок заявляет сам, — Base.Invalidate и
//     родственные методы по цепочке родителей (см. screenRect);
//   - оверлеи детей (меню, выпадающие списки) — движок рисует их через
//     OffsetContext и переводит их границы на экран;
//   - прямоугольник каретки IME и границы для скринридера — движок и
//     BuildAccessTree.

import (
	"image"
	"sync/atomic"
)

// ContentOffsetter — контейнер, показывающий своих детей со сдвигом: ребёнок с
// границами r виден на экране в r минус ContentOffset().
//
// Реализует ScrollView. Движок проверяет интерфейс на каждом виджете пути, так
// что метод обязан быть дешёвым и безопасным для вызова из любой горутины.
//
// Смещение — в системе координат самого контейнера: у вложенной прокрутки
// внешнее смещение действует на внутреннюю как на любого ребёнка, а её
// собственное — на её детей.
type ContentOffsetter interface {
	ContentOffset() image.Point
}

// contentShifter — коробка для интерфейса, чтобы держать его в atomic.Pointer.
type contentShifter struct{ src ContentOffsetter }

// baseProvider — доступ к встроенному Base. Метод неэкспортированный, поэтому
// интерфейс удовлетворяет только тип, встраивающий Base (из любого пакета), —
// то есть любой виджет этого движка.
type baseProvider interface{ baseRef() *Base }

func (b *Base) baseRef() *Base { return b }

// setContentShifter объявляет виджет контейнером со сдвигом содержимого.
func (b *Base) setContentShifter(src ContentOffsetter) {
	b.shifter.Store(&contentShifter{src: src})
}

// adoptChild записывает ребёнку его контейнер. Зовётся из Base.AddChild; тем
// же должны заниматься контейнеры, которые держат детей мимо Base (TabControl,
// DockManager), иначе область перерисовки их содержимого внутри прокрутки не
// будет переведена на экран.
func adoptChild(parent *Base, child Widget) {
	if bp, ok := child.(baseProvider); ok {
		bp.baseRef().parent.Store(parent)
	}
}

// releaseChild снимает запись, если ребёнок всё ещё числится за этим
// контейнером (за время удаления его мог усыновить другой).
func releaseChild(parent *Base, child Widget) {
	if bp, ok := child.(baseProvider); ok {
		bp.baseRef().parent.CompareAndSwap(parent, nil)
	}
}

// maxScreenRectDepth — предел подъёма по родителям: страховка от цикла в
// дереве (виджет, добавленный сам в себя, — ошибка приложения, но не повод
// зависнуть в Invalidate).
const maxScreenRectDepth = 256

// screenRect переводит r — прямоугольник в координатах ДЕТЕЙ контейнера from
// (то есть в тех же, в каких заданы Bounds его детей) — в экранные, поднимаясь
// по родителям и вычитая смещение каждого контейнера со сдвигом.
//
// Без этого ребёнок прокрутки заявлял бы область своего содержимого, а
// перерисовывалось бы не то место: сам он на экране так и остался бы
// устаревшим, а чужие пиксели обновились зря.
//
// Результат обрезается областью самого контейнера: то, что прокручено за край,
// всё равно скрыто клипом, и заявлять его — значит перерисовывать соседей
// прокрутки впустую.
//
// Пока смещение нулевое, прямоугольник возвращается как есть (обрезки нет):
// у непрокрученного содержимого поведение прежнее до пикселя.
func screenRect(from *Base, r image.Rectangle) image.Rectangle {
	for i := 0; from != nil && i < maxScreenRectDepth; i++ {
		if sh := from.shifter.Load(); sh != nil {
			if off := sh.src.ContentOffset(); off != (image.Point{}) {
				r = r.Sub(off).Intersect(from.Bounds())
				if r.Empty() {
					return r
				}
			}
		}
		from = from.parent.Load()
	}
	return r
}

// ─── Контекст со сдвигом ─────────────────────────────────────────────────────

// OffsetContext возвращает DrawContext, сдвигающий всё рисование на (-dx, -dy).
//
// ScrollView рисует детей через такую обёртку; движок тем же рисует оверлеи
// детей прокрутки. Оверлей (меню, выпадающий список) живёт в координатах
// своего виджета, а холст — в экранных: без сдвига открытое у кнопки меню
// оказывалось бы там, где кнопка стоит в содержимом, а не там, где её видно.
//
// Опциональные возможности контекста (AAShapes) сохраняются, если они были у
// внутреннего; повёрнутый текст (RotatedTextDrawer) обёртка пробрасывает, а
// остальные (мягкая тень, размытие подложки) — нет, виджеты откатываются на
// рисование без них.
func OffsetContext(ctx DrawContext, dx, dy int) DrawContext {
	if dx == 0 && dy == 0 {
		return ctx
	}
	if aa, ok := ctx.(AAShapes); ok {
		return &svOffsetCtxAA{svOffsetCtx: svOffsetCtx{inner: ctx, dx: dx, dy: dy}, aa: aa}
	}
	return &svOffsetCtx{inner: ctx, dx: dx, dy: dy}
}

// ─── Кадр обработчика события ────────────────────────────────────────────────

// eventFrame — смещение кадра виджета, которому движок сейчас доставляет
// событие мыши (упаковано: x в старших 32 битах, y в младших).
var eventFrame atomic.Uint64

func packFrame(p image.Point) uint64 {
	return uint64(uint32(int32(p.X)))<<32 | uint64(uint32(int32(p.Y)))
}

func unpackFrame(v uint64) image.Point {
	return image.Pt(int(int32(uint32(v>>32))), int(int32(uint32(v))))
}

// SetEventFrame задаёт смещение кадра виджета, получающего событие, и
// возвращает прежнее — чтобы вернуть его после обработчика.
//
// Зовёт движок вокруг обработчика виджета, стоящего внутри прокрутки. Нужно
// тому, что виджет не может узнать сам: размер экрана известен в экранных
// координатах, а событие пришло в кадре содержимого. PopupMenu.Show прижимает
// меню к краям холста — без поправки на кадр меню у виджета, прокрученного
// далеко вниз, прижималось бы к краю содержимого и улетало за экран.
//
// Состояние общее на процесс и годится только для синхронной обработки одного
// события: события приходят по одному, а вне обработчика кадр нулевой.
func SetEventFrame(off image.Point) (prev image.Point) {
	return unpackFrame(eventFrame.Swap(packFrame(off)))
}

// currentEventFrame — смещение кадра обрабатываемого сейчас события.
func currentEventFrame() image.Point {
	return unpackFrame(eventFrame.Load())
}
