package widget

// pointerowner.go — виджет, которому указатель нужен, только пока он верхний.
//
// Движение мыши движок рассылает всем виджетам, в чьих границах лежит
// указатель (или лежал на прошлом шаге), — так держится подсветка наведения.
// Перекрытия при этом не учитываются: кнопка под открытым окном тоже узнаёт,
// что указатель «над ней», и это безвредно, пока она лишь гасит подсветку.
//
// Окну чужой программы этого мало и слишком много сразу. Программа строит по
// движению свою картину — wl_pointer.enter, motion, leave — и указатель над
// панелью задач, лежащей поверх её окна, для неё должен быть ушедшим. Такой
// виджет реализует PointerOwner: движок отдаёт движение только верхнему под
// указателем владельцу (или тому, кто захватил мышь), а при смене владельца
// прежнему сообщает уход.

import "sync/atomic"

// PointerOwner — виджет, получающий движение указателя, только когда он
// верхний под указателем (или захватил мышь). Координаты — в кадре виджета,
// как у MouseMoveHandler.
type PointerOwner interface {
	// PointerOver — указатель над виджетом (или виджет держит захват).
	PointerOver(x, y int)
	// PointerOut — указатель ушёл: на другой виджет, за окно или под окно,
	// поднятое поверх.
	PointerOut()
}

// pointerOwners — сколько владельцев указателя заявили себя (SetInput у
// ExternalSurface). Пока ноль, движок не ищет владельца на каждом движении.
var pointerOwners atomic.Int32

// PointerOwnersActive сообщает движку, есть ли в процессе хоть один владелец
// указателя.
func PointerOwnersActive() bool { return pointerOwners.Load() > 0 }
