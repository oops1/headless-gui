package widget

// fontmetrics.go — вертикальные метрики шрифта для кода, которому нужно
// выровнять текст по базовой линии вне отрисовки или при смешении кеглей.
// Идёт тем же путём, что и замер ширины: через измеритель, который
// регистрирует движок (Measurers.FontMetrics).

import "math"

// FontMetrics — вертикальные метрики шрифта в ЛОГИЧЕСКИХ пикселях.
//
// Раньше их не было в публичном API: внутри движка они есть (по ним
// DrawText ставит базовую линию), но приложения их не видели. Блокнот
// разбирал TTF-файлы сам, ради одной цифры, и рисковал разойтись с движком в
// округлении; любой виджет со смешанными кеглями в строке (редактор с
// подсветкой, rich text) не мог выровнять их по общей базовой линии.
type FontMetrics struct {
	// Ascent — расстояние от верха строки до базовой линии. Ровно на столько
	// DrawText опускает базовую линию от переданного y.
	Ascent int
	// Descent — расстояние от базовой линии до низа строки (положительное).
	Descent int
	// LineGap — рекомендуемый шрифтом зазор между строками (не отрицательный).
	LineGap int
	// Height — рекомендуемый шаг между строками: Ascent + Descent + LineGap.
	Height int
}

// Доли кегля для приближения без движка. Взяты по типичным шрифтам интерфейса
// (Roboto, Go, DejaVu: подъём 0.93–0.97 em, спуск 0.2–0.25 em, зазор около
// нуля) — вертикальные метрики у этих шрифтов близки, в отличие от ширин.
const (
	approxAscentEm  = 0.95
	approxDescentEm = 0.24
	// pxPerPt — пикселей в пункте при 96 DPI: ровно так движок переводит
	// кегль в пиксели (DefaultDPI / 72).
	pxPerPt = 96.0 / 72.0
)

// MeasureUIFontMetrics возвращает вертикальные метрики шрифта по имени и
// кеглю sizePt — вне отрисовки, там же, где работает MeasureUITextFont.
//
// Порядок аргументов тот же, что у MeasureUITextFont: кегль, затем семейство.
// Пустое имя — шрифт по умолчанию; незарегистрированное имя движок тоже
// подменяет шрифтом по умолчанию, как и при отрисовке, поэтому метрики всегда
// те, по которым текст реально нарисуют.
//
// Метрики — в логических пикселях, как и ширины MeasureUIText: при HiDPI
// движок переводит физические значения в логические.
//
// Без зарегистрированного движка (headless-тесты без engine.New, остановленный
// движок) возвращается приближение по доле кегля: нули заставили бы вызывающего
// делить на ноль или схлопнуть строки, а грубая, но правдоподобная высота
// строки оставляет раскладку рабочей — так же, как эвристика ширины в
// MeasureUIText. Для неположительного кегля шрифта нет — все нули.
func MeasureUIFontMetrics(sizePt float64, family string) FontMetrics {
	if sizePt <= 0 {
		return FontMetrics{}
	}
	if fn := activeSet().FontMetrics; fn != nil {
		a, d, g := fn(sizePt, family)
		if a < 0 {
			a = 0
		}
		if d < 0 {
			d = 0
		}
		if g < 0 {
			g = 0
		}
		return FontMetrics{Ascent: a, Descent: d, LineGap: g, Height: a + d + g}
	}
	return approxFontMetrics(sizePt)
}

// approxFontMetrics — приближение метрик по кеглю, когда движка нет.
func approxFontMetrics(sizePt float64) FontMetrics {
	em := sizePt * pxPerPt
	// Подъём не меньше двух пикселей, спуск не меньше одного: при крошечном
	// кегле округление дало бы нули, а Ascent > Descent > 0 — инвариант, на
	// который опираются вызывающие.
	a := int(math.Round(em * approxAscentEm))
	if a < 2 {
		a = 2
	}
	d := int(math.Round(em * approxDescentEm))
	if d < 1 {
		d = 1
	}
	if d >= a {
		d = a - 1
	}
	return FontMetrics{Ascent: a, Descent: d, Height: a + d}
}
