package widget

import (
	"image"
	"image/color"
)

// bevel.go — объёмная рамка Windows 2000, одна на весь движок.
//
// Раньше «классический» вид жил ветками `if Classic3D` внутри каждого
// виджета, а цвета брались из глобальной темы. Теперь то же самое рисуется
// по данным: тема отдаёт тройку цветов, а компонент только передаёт их сюда
// и не знает, какая тема активна.
//
// Реализация одна намеренно. Их было две — эта и drawBevelRaised/Sunken в
// themes_presets.go, — и они успели разойтись: панель задач рисовала
// внутреннюю грань с обеих сторон, кнопки — с одной. Рядом на экране это
// видно: у кнопки «Пуск» рамка выходила толще, чем у кнопки в окне.

// DrawBevel рисует объёмную рамку Windows 2000 по цветам, заданным темой.
//
// Геометрия — та же, что у настоящей Windows: внешнее кольцо целиком, плюс
// внутренняя грань ТОЛЬКО с одной стороны. У выпуклой рамки это тень снизу
// и справа, у утопленной — самый тёмный цвет сверху и слева; с другой
// стороны наружу смотрит лицо элемента, и линии там нет. Внутренняя грань с
// обеих сторон делает рамку двухпиксельной по всему периметру — толще, чем
// нужно, и заметно рядом с рамкой, нарисованной верно.
//
// sunken=false — выпуклая рамка (кнопка в покое); sunken=true — утопленная
// (поле ввода, дорожка прогресса, нажатая кнопка): грани меняются местами.
func DrawBevel(ctx DrawContext, r image.Rectangle, light, shadow, dark color.RGBA, sunken bool) {
	if r.Dx() < 2 || r.Dy() < 2 {
		return
	}
	x, y, w, h := r.Min.X, r.Min.Y, r.Dx(), r.Dy()

	outerTL, outerBR := light, dark
	if sunken {
		outerTL, outerBR = shadow, light
	}
	ctx.DrawHLine(x, y, w, outerTL)
	ctx.DrawVLine(x, y, h, outerTL)
	ctx.DrawHLine(x, y+h-1, w, outerBR)
	ctx.DrawVLine(x+w-1, y, h, outerBR)

	// Внутренняя грань — от неё рамка и читается объёмной. На рамке уже́ в
	// три точки внешнее кольцо занимает всё: рисовать её некуда.
	if w < 4 || h < 4 {
		return
	}
	if sunken {
		ctx.DrawHLine(x+1, y+1, w-2, dark)
		ctx.DrawVLine(x+1, y+1, h-2, dark)
		return
	}
	ctx.DrawHLine(x+1, y+h-2, w-2, shadow)
	ctx.DrawVLine(x+w-2, y+1, h-2, shadow)
}
