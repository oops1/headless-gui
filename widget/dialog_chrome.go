// dialog_chrome.go — диалог без штатной полосы заголовка.
//
// Диалог всегда рисовал свою полосу во всю ширину: подпись слева, ✕ справа.
// Значит, верхняя полоса принадлежала движку, а любая боковая панель начиналась
// только под ней — левый верхний угол приложению был недоступен. Окно настроек,
// устроенное как вертикальные вкладки браузера (панель навигации во всю левую
// сторону, заголовок внутри неё), воспроизвести было нельзя.
//
// Здесь две недостающие детали, которые заказчик и назвал: выключатель штатной
// полосы и способ сказать, какая часть содержимого работает как область
// перетаскивания окна.
package widget

import "image"

// SetChromeless убирает штатную полосу заголовка: подпись, ✕ и разделительную
// линию рисует приложение.
//
// Область содержимого при этом начинается от самого верха диалога, а
// перетаскивание надо объявить через AddDragArea — иначе окно нечем будет
// сдвинуть: полосы, за которую его тянули, больше нет.
//
// Кнопка ✕ убирается вместе с полосой: рисовать её поверх чужой шапки движок
// не вправе, он не знает, что там у приложения. Закрытие по Escape остаётся,
// а крестик приложение рисует само и зовёт RequestClose.
func (d *Dialog) SetChromeless(v bool) {
	if d.chromeless == v {
		return
	}
	d.chromeless = v
	d.ShowCloseButton = !v
	if d.closeBtn != nil {
		d.closeBtn.SetVisible(!v)
	}
	// Высота полосы влияет и на область содержимого, и на её собственную
	// начинку (кнопка сворачивания, виджет приложения) — перекладываем.
	d.SetBounds(d.bounds)
	d.Invalidate()
}

// IsChromeless сообщает, убрана ли штатная полоса заголовка.
func (d *Dialog) IsChromeless() bool { return d.chromeless }

// titleH возвращает фактическую высоту полосы заголовка.
//
// Одна точка правды: и отрисовка, и область содержимого, и хит-тест
// перетаскивания спрашивают её. Иначе выключение полосы пришлось бы помнить в
// трёх местах, и первое же забытое дало бы содержимое, начинающееся под
// несуществующей полосой.
func (d *Dialog) titleH() int {
	if d.chromeless {
		return 0
	}
	return d.TitleHeight
}

// AddDragArea объявляет прямоугольник содержимого областью перетаскивания окна.
//
// Координаты — ОТНОСИТЕЛЬНО левого верхнего угла диалога, а не абсолютные:
// диалог двигают, и абсолютные пришлось бы пересчитывать после каждого
// перетаскивания — то есть после каждого использования этой самой области.
//
//	dlg.SetChromeless(true)
//	dlg.AddDragArea(image.Rect(0, 0, 240, 48)) // шапка боковой панели
//
// Нажатие в такой области тащит окно ровно так же, как раньше нажатие на
// полосу заголовка — включая вынос в нативное окно (OnDragMove).
//
// Объявленная область СИЛЬНЕЕ лежащих в ней виджетов. У штатной полосы правило
// обратное — там виджет (✕) забирает нажатие себе, — но шапку, нарисованную
// приложением, целиком составляют его же виджеты, и проверка «под курсором
// чей-то ребёнок» отменяла бы перетаскивание всегда. Вырезать из области свои
// кнопки — забота того, кто её объявил: объявите две области по бокам от
// кнопки вместо одной сплошной.
func (d *Dialog) AddDragArea(r image.Rectangle) {
	if r.Empty() {
		return
	}
	d.dragAreas = append(d.dragAreas, r)
}

// ClearDragAreas забывает объявленные области перетаскивания.
func (d *Dialog) ClearDragAreas() { d.dragAreas = nil }

// dragAreaHit сообщает, попадает ли точка в объявленную область перетаскивания.
func (d *Dialog) dragAreaHit(pt image.Point) bool {
	if len(d.dragAreas) == 0 {
		return false
	}
	off := d.bounds.Min
	for _, r := range d.dragAreas {
		if pt.In(r.Add(off)) {
			return true
		}
	}
	return false
}

// ─── Окно (widget.Window) ───────────────────────────────────────────────────

// AddDragArea объявляет прямоугольник содержимого областью перетаскивания окна.
//
// Нужна borderless-окну (WindowStyleNone): полосы заголовка у него нет, а
// значит и тащить его было не за что — WantsCapture у такого окна отвечал
// «нет» безусловно. Приложение, рисующее свою шапку, теперь говорит движку, где
// она.
//
// Координаты — ОТНОСИТЕЛЬНО левого верхнего угла окна: окно двигают, и
// абсолютные пришлось бы пересчитывать после каждого перетаскивания.
func (w *Window) AddDragArea(r image.Rectangle) {
	if r.Empty() {
		return
	}
	w.dragAreas = append(w.dragAreas, r)
}

// ClearDragAreas забывает объявленные области перетаскивания окна.
func (w *Window) ClearDragAreas() { w.dragAreas = nil }

// dragAreaHit сообщает, попадает ли точка в объявленную область перетаскивания.
func (w *Window) dragAreaHit(pt image.Point) bool {
	if len(w.dragAreas) == 0 {
		return false
	}
	off := w.bounds.Min
	for _, r := range w.dragAreas {
		if pt.In(r.Add(off)) {
			return true
		}
	}
	return false
}
