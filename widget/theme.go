// Package widget — активная тема (цвета по умолчанию для конструкторов виджетов).
//
// win10 — глобальная переменная, хранящая текущую тему.
// Инициализируется DarkTheme. Обновляется через ApplyGlobalTheme (вызывается engine.SetTheme).
package widget

// win10 — текущая активная тема; используется всеми New*-конструкторами.
var win10 = *DarkTheme()

// CurrentTheme возвращает копию активной темы.
//
// Копия, а не указатель на глобал: тема — общее состояние процесса, и отдать
// на неё ссылку значит позволить менять её мимо ApplyGlobalTheme, то есть
// мимо блокировки кадра, под которой эта смена обязана происходить.
//
// Нужна тому, кто красит виджет, созданный ПОСЛЕ смены темы: конструкторы
// берут цвета из этой же переменной, но виджеты, кеширующие палитру у себя
// (DataGridWidget), красятся отдельным вызовом ApplyTheme.
func CurrentTheme() *Theme {
	t := win10
	return &t
}
