// togglebutton.go — кнопка-переключатель: состояние «нажата» живёт между
// кликами.
//
// `<ToggleButton>` в разметке разбирался тем же сборщиком, что и `<Button>`, и
// превращался в обычную кнопку: поля состояния у неё нет, а «нажатость»
// показывалась только пока держат мышь. Панель фильтров — восемь кнопок
// «показывать/не показывать», — выразить этим было нечем, и приложению
// приходилось держать состояние у себя, а вид подделывать, перекрашивая
// Background на каждый клик и на каждую смену темы.
//
// Здесь состояние переезжает в саму кнопку. Отдельного типа нет намеренно:
// ToggleButton в WPF отличается от Button ровно этим состоянием, а не
// раскладкой, иконками, командами или подписками — заводить ради одного поля
// второй тип со всем этим хозяйством значило бы дублировать button.go
// целиком.
package widget

import "sync/atomic"

// SetToggle делает кнопку переключателем (или возвращает обычной).
//
// У переключателя клик меняет устойчивое состояние «нажата», и кнопка сама
// красится в PressedBG, пока состояние включено.
func (btn *Button) SetToggle(v bool) {
	if atomic.SwapInt32(&btn.isToggle, b2i(v)) == b2i(v) {
		return
	}
	if !v {
		atomic.StoreInt32(&btn.checked, 0)
	}
	btn.Invalidate()
}

// IsToggle сообщает, является ли кнопка переключателем.
func (btn *Button) IsToggle() bool { return atomic.LoadInt32(&btn.isToggle) == 1 }

// SetChecked задаёт состояние переключателя.
//
// Работает и на обычной кнопке — тогда состояние просто нигде не меняется
// само: приложению бывает нужно нарисовать «выбранный» пункт панели, не
// отдавая ему поведение переключателя.
//
// OnCheckedChanged отсюда НЕ зовётся: программная установка состояния — это
// не действие пользователя, и обработчик, который сам зовёт SetChecked (обычная
// синхронизация группы кнопок), иначе ушёл бы в рекурсию.
func (btn *Button) SetChecked(v bool) {
	if atomic.SwapInt32(&btn.checked, b2i(v)) != b2i(v) {
		btn.Invalidate()
	}
}

// IsChecked сообщает состояние переключателя.
func (btn *Button) IsChecked() bool { return atomic.LoadInt32(&btn.checked) == 1 }

// Toggle переключает состояние и сообщает об этом OnCheckedChanged.
//
// Ровно то, что делает клик по кнопке-переключателю. Отдельно нужен для
// горячих клавиш и пунктов меню, дублирующих кнопку.
func (btn *Button) Toggle() {
	v := !btn.IsChecked()
	btn.SetChecked(v)
	if btn.OnCheckedChanged != nil {
		btn.OnCheckedChanged(v)
	}
}
