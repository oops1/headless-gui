package widget

// touch.go — касания: событие, фазы и интерфейс обработчика.
//
// Касания — отдельный вид ввода, а не «мышь пальцем». Мышь у окна одна, пальцев
// может быть несколько, и у каждого своя история от касания до отрыва; свести
// это к одному указателю — значит потерять щипок и два пальца вообще. Поэтому у
// касания свой тип события и свой интерфейс, а движок не превращает его в мышь
// сам: приложение, ничего не знающее о касаниях, получает от ОС ту мышь, что
// получало всегда (см. engine.SendTouch и window.Window.SetTouchEnabled).

import (
	"fmt"
	"time"
)

// TouchPhase — этап жизни касания.
type TouchPhase int

const (
	// TouchBegan — палец коснулся экрана.
	TouchBegan TouchPhase = iota
	// TouchMoved — палец сдвинулся (или бэкенд подтвердил положение).
	TouchMoved
	// TouchEnded — палец оторван.
	TouchEnded
	// TouchCancelled — касание отменено системой: его забрал другой обработчик
	// (системный жест, потеря захвата), окно потеряло ввод. Отрыва не будет;
	// действие, которое палец начал, надо откатить, а не завершить.
	TouchCancelled
)

// String — имя фазы для логов и сообщений тестов.
func (p TouchPhase) String() string {
	switch p {
	case TouchBegan:
		return "Began"
	case TouchMoved:
		return "Moved"
	case TouchEnded:
		return "Ended"
	case TouchCancelled:
		return "Cancelled"
	}
	return fmt.Sprintf("TouchPhase(%d)", int(p))
}

// Terminal — фаза последняя в жизни касания (отрыв или отмена).
func (p TouchPhase) Terminal() bool { return p == TouchEnded || p == TouchCancelled }

// TouchEvent — событие одного пальца.
type TouchEvent struct {
	// ID — идентификатор касания: один и тот же от TouchBegan до TouchEnded или
	// TouchCancelled и разный у одновременных пальцев. После отрыва ОС вправе
	// выдать тот же номер новому касанию — различай их по фазе Began.
	ID int
	// X, Y — точка касания.
	//
	// Движок принимает их в ФИЗИЧЕСКИХ пикселях окна (как SendMouseMove), а
	// виджету отдаёт в ЛОГИЧЕСКИХ и в кадре самого виджета (у ребёнка прокрутки —
	// в координатах содержимого, как у мыши). Пороги распознавателя жестов
	// (GestureConfig) заданы в логических пикселях.
	X, Y  int
	Phase TouchPhase
	// Time — момент события по монотонным часам источника (бэкенды отдают
	// временную метку ОС, переведённую в time.Duration). Нужен для скорости и
	// длительности; только разности имеют смысл, начало отсчёта не определено.
	//
	// Ноль — «не задано»: engine.SendTouch тогда подставляет время прихода
	// события. Распознаватель жестов без времени не сможет отличить тап от
	// долгого нажатия и посчитать скорость свайпа.
	Time time.Duration

	// Pressure — нажим пальца, от 0 до 1; 0 — «неизвестно». Устройство, не
	// измеряющее нажим (ёмкостный экран без датчика силы), и бэкенд, не умеющий
	// его читать, дают 0, а не «лёгкое касание»: различить их нельзя, и приложение
	// не должно ждать от нуля смысла. Wayland давления не передаёт вовсе.
	Pressure float64
	// Major, Minor — большая и малая оси эллипса контакта в пикселях (диаметры, не
	// радиусы); 0 — неизвестно. Координатная система та же, что у X, Y: движку
	// приходят физические пиксели, виджету — логические. Win32 знает только
	// охватывающий прямоугольник контакта, и тогда Major — его длинная сторона, а
	// Minor — короткая.
	Major, Minor float64
	// Orientation — угол большой оси эллипса от вертикали по часовой стрелке, в
	// градусах; 0 — вертикально или неизвестно (при Major == 0 поле не значимо).
	Orientation float64
}

// HasPressure сообщает, что нажим известен.
func (e TouchEvent) HasPressure() bool { return e.Pressure > 0 }

// HasContact сообщает, что известна площадь контакта.
func (e TouchEvent) HasContact() bool { return e.Major > 0 }

// TouchHandler реализуется виджетами, принимающими касания.
//
// Движок спрашивает виджетов от самого глубокого под точкой касания к корню (как
// нажатие мыши): первый, чей OnTouch на фазе TouchBegan вернул true, становится
// владельцем касания и получает ВСЕ его события — Moved, Ended или Cancelled — где
// бы палец ни оказался и что бы ни лежало под ним. Захват по ID, поэтому два
// пальца на разных виджетах ведут два независимых разговора.
//
// Возвращаемое значение на остальных фазах ничего не меняет. Виджет, который на
// TouchBegan вернул false, о дальнейших событиях этого касания не узнает.
// Касание, которого не взял никто, движок мышью не подменяет: engine.SendTouch
// просто вернёт false. Приложение, не знающее о касаниях, мышь от ОС получает
// как раньше — бэкенд ловит касания, только если окно включило их явно
// (window.Window.SetTouchEnabled); а включившее окно само превращает «ничьё»
// касание в левую кнопку мыши, чтобы обычные кнопки и меню остались рабочими.
type TouchHandler interface {
	OnTouch(ev TouchEvent) bool
}
