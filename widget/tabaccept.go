package widget

// TabAcceptor — виджет, которому Tab нужен как символ, а не как переход фокуса:
// редактор кода, сравнение файлов (WPF: AcceptsTab="True").
//
// Движок перехватывал Tab до доставки фокусному виджету и отдавал его обходу
// фокуса, так что OnKeyEvent Tab не видел вовсе — написанная обработка табуляции
// в редакторе не срабатывала никогда.
//
// Опциональным интерфейсом, а не полем Base: он нужен единицам, и спрашивать
// его у каждого виджета при каждом Tab незачем — движок спрашивает только того,
// у кого фокус. Метод, а не флаг: виджет вправе принимать Tab не всегда —
// например, пока не в режиме «только чтение».
//
// Ctrl+Tab и Ctrl+Shift+Tab остаются навигацией — как в WPF: иначе из
// редактора, забравшего Tab, было бы не выйти с клавиатуры.
type TabAcceptor interface {
	AcceptsTab() bool
}

// acceptsTab сообщает, забирает ли виджет Tab себе.
func acceptsTab(w Widget) bool {
	ta, ok := w.(TabAcceptor)
	return ok && ta.AcceptsTab()
}

// WantsTab — может ли событие Tab уйти фокусному виджету, а не обходу фокуса.
// Экспортирован для движка: решение одно на всех, и держать его в двух местах
// значило бы однажды разойтись в том, что считать навигацией.
func WantsTab(focused Widget, ev KeyEvent) bool {
	if focused == nil || ev.Code != KeyTab || ev.Mod&ModCtrl != 0 {
		return false
	}
	return acceptsTab(focused)
}
