// dialog_resize.go — диалог с изменяемым размером.
//
// Размер задавался один раз в NewDialog и больше не менялся: ни Resizable, ни
// MinWidth/MinHeight у диалога не было, а нативный хост модалки закреплял это
// намертво — SetResizable(false) и минимум ровно по диалогу. Сам Dialog не
// переопределял SetBounds, поэтому даже программная смена размера не
// пересчитывала раскладку добавленного содержимого: кнопка ✕ оставалась на
// прежнем месте, а дети — прежнего размера.
//
// Из-за этого окно настроек, которое обязано тянуться, приходилось делать не
// диалогом, а отдельным окном — теряя модальность.
package widget

import "image"

// dialogMinW/dialogMinH — во что диалог не даёт себя сжать, если приложение не
// задало своего минимума.
//
// Меньше этого в диалоге не помещается ничего осмысленного: заголовок с
// кнопкой ✕ занимает верх, отступы — края, и на содержимое остаются считанные
// точки. Пустой диалог в четыре пикселя — не то, что человек хотел получить,
// потянув за угол.
const (
	dialogMinW = 200
	dialogMinH = 120
)

// SetResizable разрешает менять размер диалога.
//
// По умолчанию ВЫКЛЮЧЕНО: диалог с вопросом и двумя кнопками тянуть незачем, а
// нативный хост модалки до сих пор создавал окно нерастяжимым. Включение
// меняет и его: окно ОС получает рамку с ресайзом и минимум из MinWidth/
// MinHeight, а не из размера диалога.
func (d *Dialog) SetResizable(v bool) {
	if d.resizable == v {
		return
	}
	d.resizable = v
	d.Invalidate()
}

// IsResizable сообщает, разрешено ли менять размер диалога.
func (d *Dialog) IsResizable() bool { return d.resizable }

// SetMinSize задаёт наименьший размер диалога в логических пикселях.
//
// Ноль по оси означает «умолчание» (dialogMinW/dialogMinH), а не «без
// ограничения»: диалог, сжатый в точку, нельзя ни закрыть, ни растянуть
// обратно — единственные его органы управления исчезают вместе с ним.
func (d *Dialog) SetMinSize(w, h int) {
	d.minW, d.minH = w, h
	// Текущий размер мог оказаться меньше нового минимума.
	d.SetBounds(d.bounds)
}

// MinSize возвращает действующий наименьший размер диалога.
func (d *Dialog) MinSize() (int, int) {
	w, h := d.minW, d.minH
	if w <= 0 {
		w = dialogMinW
	}
	if h <= 0 {
		h = dialogMinH
	}
	return w, h
}

// SetContent назначает виджет, заполняющий область содержимого.
//
// Он и только он растягивается при изменении размера диалога. Растягивать ВСЕ
// дочерние виджеты нельзя: диалоги этого движка расставляют кнопки и подписи
// абсолютными координатами внутри себя, и «каждый ребёнок занимает всю
// область» превратило бы MessageBox в стопку виджетов друг поверх друга.
//
// Приложению, которому нужен тянущийся диалог, достаточно положить внутрь один
// контейнер — StackPanel, DockPanel, Grid — и отдать его сюда.
func (d *Dialog) SetContent(w Widget) {
	if d.content == w {
		return
	}
	if d.content != nil {
		d.RemoveChild(d.content)
	}
	d.content = w
	if w == nil {
		return
	}
	d.AddChild(w)
	if cb := d.ContentBounds(); !cb.Empty() {
		w.SetBounds(cb)
	}
}

// Content возвращает виджет содержимого (nil, если не задан).
func (d *Dialog) Content() Widget { return d.content }

// SetBounds задаёт границы диалога, двигая содержимое вместе с ним.
//
// Дети СДВИГАЮТСЯ на ту же величину, а не растягиваются: они расставлены
// абсолютными координатами внутри диалога, и это единственный способ
// сохранить их раскладку при переносе. Растягивается только виджет,
// назначенный SetContent.
//
// Кнопка ✕ переезжает в новый правый верхний угол отдельно: она не
// содержимое, а часть заголовка, и при изменении ШИРИНЫ простого сдвига ей
// мало.
func (d *Dialog) SetBounds(r image.Rectangle) {
	minW, minH := d.MinSize()
	if r.Dx() < minW {
		r.Max.X = r.Min.X + minW
	}
	if r.Dy() < minH {
		r.Max.Y = r.Min.Y + minH
	}

	old := d.bounds
	d.Base.SetBounds(r)

	if dx, dy := r.Min.X-old.Min.X, r.Min.Y-old.Min.Y; dx != 0 || dy != 0 {
		for _, child := range d.Children() {
			// Меню, прикреплённое к диалогу, позиционирует себя само.
			if _, ok := child.(*PopupMenu); ok {
				continue
			}
			ShiftWidget(child, dx, dy)
		}
	}

	if d.closeBtn != nil {
		top := r.Min.Y + (d.TitleHeight-dlgCloseSize)/2
		d.closeBtn.SetBounds(image.Rect(
			r.Max.X-dlgCloseSize-6, top,
			r.Max.X-6, top+dlgCloseSize))
	}

	// Боковая панель занимает колонку до верхнего края — её раскладка идёт
	// раньше содержимого, которое от неё отступает.
	d.layoutNavPanel()

	// Полоса заголовка: кнопка сворачивания и начинка приложения (titlebar.go).
	// Ширина полосы меняется вместе с диалогом, поэтому раскладка здесь, а не
	// только в момент их установки.
	d.layoutTitleBar()

	if d.content != nil {
		if cb := d.ContentBounds(); !cb.Empty() {
			d.content.SetBounds(cb)
		}
	}
}

// Resize меняет размер диалога, оставляя левый верхний угол на месте.
//
// Отдельно от SetBounds, потому что приложение думает размером, а не
// прямоугольником: «сделать окно настроек шире» не должно требовать вычислять
// координаты второго угла.
func (d *Dialog) Resize(w, h int) {
	b := d.bounds
	d.SetBounds(image.Rect(b.Min.X, b.Min.Y, b.Min.X+w, b.Min.Y+h))
}
