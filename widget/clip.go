package widget

// clip.go — вложенное отсечение области рисования.
//
// `SetClip` ЗАМЕНЯЕТ область отсечения, а `ClearClip` снимает её целиком.
// Для виджета, который рисует сам себя, этого довольно, но стоит положить
// его внутрь другого — и правило ломается: ребёнок, сузивший область своей
// частью, в конце снимает сужение ВМЕСТЕ с тем, которое поставил родитель.
// Дальше рисуют уже без него, и содержимое прокрутки вылезает за её края.
//
// Правило простое: ребёнок не рисует там, где не рисует родитель. Здесь оно
// и выражено — сужение идёт пересечением с текущей областью, а снятие
// возвращает её, а не отменяет.
//
// Отдельной функцией, а не методом контекста: `DrawContext` реализуют и
// приложения (свои обёртки, записывающие контексты в тестах), и добавление
// метода в интерфейс сломало бы их сборку.

import "image"

// PushClip сужает область рисования до пересечения r с нынешней и
// возвращает функцию, которая вернёт прежнюю.
//
// Применяется так:
//
//	defer PushClip(ctx, inner)()
//
// Возвращаемую функцию звать обязательно — иначе сужение останется
// соседям. Вызывать её дважды безопасно: второй раз просто повторит
// восстановление.
func PushClip(ctx DrawContext, r image.Rectangle) func() {
	if ctx == nil {
		return func() {}
	}
	prev := ctx.Clip()
	ctx.SetClip(r.Intersect(prev))
	return func() { ctx.SetClip(prev) }
}

// ClipRect — пересечение r с нынешней областью рисования, без её изменения.
//
// Нужно там, где виджет сам решает, что рисовать: сравнить свою часть с
// видимой и пропустить невидимое.
func ClipRect(ctx DrawContext, r image.Rectangle) image.Rectangle {
	if ctx == nil {
		return r
	}
	return r.Intersect(ctx.Clip())
}
