// dialog_closing.go — право остановить закрытие диалога.
//
// Закрытие по Escape и по кнопке ✕ шло через замыкание, которое движок вешает
// в ShowModal: оно звало OnCancel и СРАЗУ ЖЕ CloseModal, независимо от того,
// что обработчик успел сделать. То есть CancelAction был уведомлением
// постфактум, а не правом вето.
//
// Диалогу с несохранёнными изменениями этого мало: на Escape он обязан
// спросить «Сохранить изменения?» и дождаться ответа. Показать второй диалог
// из CancelAction было можно, но первый движок всё равно выталкивал из стека в
// том же вызове — приложению приходилось замечать это по IsModal() и
// показывать диалог заново, теряя кадр.
package widget

// CanClose сообщает движку, разрешено ли закрывать диалог сейчас.
//
// Реализует опциональный интерфейс, который движок спрашивает ПЕРЕД закрытием
// модалки по Escape или ✕. Диалог без OnClosing отвечает «да» — прежнее
// поведение сохраняется у всех, кто хук не задавал.
func (d *Dialog) CanClose() bool {
	if d.OnClosing == nil {
		return true
	}
	return d.OnClosing()
}
