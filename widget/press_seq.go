// press_seq.go — сквозная нумерация нажатий мыши.
//
// Движок гасит Dismissable-виджеты (dropdown, popup-меню) вне пути клика ДО
// того, как событие дойдёт до виджетов. Из-за этого кнопка, которая владеет
// меню, но лежит в ДРУГОМ виджете — шеврон полосы вкладок живёт в Window, а
// меню висит отдельным ребёнком, — не может отличить «меню было закрыто
// раньше» от «его закрыло моё же нажатие», и вместо сворачивания открывает
// меню заново.
//
// Номер нажатия решает это без привязки к кадрам: движок увеличивает счётчик
// перед разбором каждого нажатия, гаснущее меню запоминает текущий номер, а
// кнопка сравнивает его со своим. Без движка (юнит-тесты, чужой хост)
// счётчик остаётся нулевым, а 0 означает «нажатий не было» — сравнение тогда
// всегда ложно и поведение прежнее.
package widget

import "sync/atomic"

var pressSeq atomic.Uint64

// BumpPressSeq открывает новое нажатие мыши. Вызывается движком в начале
// разбора нажатия — до гашения overlay'ев и доставки события виджетам.
func BumpPressSeq() { pressSeq.Add(1) }

// CurrentPressSeq возвращает номер текущего (последнего начатого) нажатия.
// 0 — нажатий ещё не было.
func CurrentPressSeq() uint64 { return pressSeq.Load() }
