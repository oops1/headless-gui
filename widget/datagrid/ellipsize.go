// ellipsize.go — обрезание длинного текста многоточием.
//
// Текст ячейки рисовался целиком и полагался на отсечение по прямоугольнику:
// длинный адрес обрывался посреди буквы, без всякого знака, что он длиннее
// колонки. Отличить «Ivan» от обрезанного «Ivanov» было нельзя.
package datagrid

// EllipsizeText укорачивает строку до maxW пикселей, добавляя «…».
//
// Экспортирована ради шаблонных колонок: рисуют они сами, а мерить текст и
// резать его по границам рун — работа, которую незачем писать заново в каждом
// приложении.
//
// Меряет тем же контекстом, которым будет рисовать, поэтому результат верен
// для текущего шрифта и кегля. Поиск двоичный: у длинной строки линейный
// подбор означал бы сотню измерений на ячейку, а измерение текста — не самая
// дешёвая операция кадра.
func EllipsizeText(ctx DrawContextBridge, s string, maxW int, sizePt float64) string {
	if s == "" || maxW <= 0 || ctx == nil {
		return s
	}
	if ctx.MeasureText(s, sizePt) <= maxW {
		return s
	}
	r := []rune(s)
	lo, hi := 0, len(r) // максимальный префикс, влезающий вместе с «…»
	for lo < hi {
		mid := (lo + hi + 1) / 2
		if ctx.MeasureText(string(r[:mid])+"…", sizePt) <= maxW {
			lo = mid
		} else {
			hi = mid - 1
		}
	}
	if lo == 0 {
		// Не влезает даже одна буква с многоточием. Показываем одно
		// многоточие: пустая ячейка соврала бы, что значения нет вовсе.
		return "…"
	}
	return string(r[:lo]) + "…"
}
