// Package x11 — бэкенд нативного окна X11 (ADR-0013): X11Window на голом
// протоколе X11 через unix-сокет, чистый Go без CGO и Xlib.
//
// Здесь окно и всё, что живёт на его внутренностях: ввод (мышь, касания
// XInput2, клавиатура, автоповтор, захват клавиатуры и указателя,
// lock-клавиши XKB), полный экран и мониторы RandR, начальное положение и
// подсказки WM, значок _NET_WM_ICON, курсоры, формы и прозрачность попапов
// (SHAPE, ARGB), MIT-SHM, буфер обмена (тексты, HTML, картинки по INCR,
// файлы, XFIXES), перетаскивание XDND, раскладки, активация и «поверх всех».
// Окно прячется в трей и возвращается (HideToTray, RestoreFromTray); сами
// иконка в трее и уведомления — возможность platform/tray, окна они не касаются.
//
// Программы этот пакет не импортируют: X11Window и NewNativeWindow приходят
// через фасад window. Пакет собирается и на других ОС (переносимый разбор
// протокола с тестами), но окна там нет.
