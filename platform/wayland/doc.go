// Package wayland — бэкенд нативного окна Wayland (ADR-0013): WaylandWindow на
// голом протоколе Wayland (xdg-shell, wl_shm) через unix-сокет, чистый Go без
// CGO и libwayland.
//
// Здесь окно и всё, что живёт на его внутренностях: ввод (указатель, касания,
// клавиатура с раскладкой XKB, автоповтор, IME text-input-v3, захват
// клавиатуры и указателя, lock-клавиши и виртуальная клавиатура), полный
// экран и мониторы wl_output/xdg_output, начальное положение, масштаб
// (fractional-scale, viewporter), значок xdg-toplevel-icon, курсоры
// (cursor-shape или свои картинки), попапы xdg_popup с регионами, буфер
// обмена и перетаскивание wl_data_device, активация xdg-activation.
// Размер из configure для плавающего окна с запретом ресайза не принимается:
// окно держит размер фиксации (floatingSize, W9). Трей и уведомления встроены из
// platform/tray.
//
// Программы этот пакет не импортируют: WaylandWindow и NewNativeWindow
// приходят через фасад window. Пакет собирается и на других ОС (переносимый
// разбор протокола с тестами), но окна там нет.
