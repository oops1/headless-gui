package native

// style.go — вид и поведение нативного окна (window.Style) и необязательные
// возможности бэкенда: стиль, владелец, Z-порядок, положение после показа
// (ADR-0013 §4). Окно ядра (window/core) зовёт их напрямую и отвечает false,
// если бэкенд возможности не объявил.

// Style — вид и поведение нативного окна.
//
// Нулевое значение — обычное окно: оно и так без рамки ОС (рамку и заголовок
// рисует приложение), с зонами изменения размера по краям, со скруглением и
// тенью ОС там, где ОС их даёт, с кнопкой на панели задач.
type Style struct {
	// Borderless — окно целиком принадлежит приложению: нет зон изменения
	// размера по краям, скругления углов и тени ОС (окно RemoteApp рисует
	// свою рамку и тень само).
	Borderless bool
	// Owned — окно принадлежит владельцу (Window.SetOwner): всегда над ним по
	// Z, сворачивается и восстанавливается вместе с ним. Владельца задаёт
	// SetOwner; SetStyle с Owned=false владельца снимает, а Owned=true без
	// владельца невыполнимо.
	Owned bool
	// Tool — окно-инструмент: без кнопки на панели задач и вне переключателя
	// окон (Alt+Tab).
	Tool bool
}

// Styler — бэкенд применяет Borderless и Tool (Owned — через OwnerSetter).
//
// До Create стиль запоминается и закладывается в создание окна (окно
// показывается уже в Create, и стиль, применённый после, был бы виден
// переходом); после — меняется у живого окна. Возвращает стиль, который
// действует после вызова: часть, которую бэкенд не умеет, он не применяет, и
// в ответе её нет (поле Owned бэкенд не читает и не заполняет).
//
//facadegen:skip
type Styler interface {
	ApplyStyle(s Style) Style
}

// OwnerSetter — бэкенд делает окно принадлежащим owner (nil — снимает
// владельца), без модальности: в отличие от владельца модального диалога,
// владелец остаётся доступен. До Create владелец запоминается и закладывается
// в создание окна (owner к этому времени уже должен быть создан). true —
// сделано (на X11 — отправлено); false — owner другого бэкенда, ещё не создан
// или уже закрыт, окно не встало над ним или поток владельца не ответил
// вовремя (Win32), или бэкенд этого не умеет.
//
//facadegen:skip
type OwnerSetter interface {
	SetOwnerWindow(owner NativeWindow) bool
}

// Stacker — бэкенд меняет Z-порядок окна без активации: RaiseWindow — наверх,
// LowerWindow — вниз. true — запрос выполнен (на X11 — отправлен: решает
// оконный менеджер).
//
//facadegen:skip
type Stacker interface {
	RaiseWindow() bool
	LowerWindow() bool
}

// Positioner — бэкенд ставит уже показанное окно на место с честным ответом
// (NativeWindow.SetPosition и GetPosition ответа не дают). Координаты —
// экранные физические, как у SetInitialBounds и Monitor.Bounds. MoveTo
// отвечает false у окна, которое двигать нельзя (ещё не создано, развёрнуто,
// на весь экран, свёрнуто); ScreenPosition — ok=false, когда положение
// неизвестно.
//
//facadegen:skip
type Positioner interface {
	MoveTo(x, y int) bool
	ScreenPosition() (x, y int, ok bool)
}
