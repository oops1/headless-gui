// Package win32 — бэкенд нативного окна Windows (ADR-0013): Win32Window на
// user32, gdi32, dwmapi и OLE, чистый Go без CGO.
//
// Здесь окно и всё, что живёт на его внутренностях: ввод (мышь, касания,
// клавиатура, IME, захват клавиатуры и указателя, lock-клавиши), полный
// экран и мониторы, начальное положение, значок и курсоры, регионы и
// прозрачность попапов, превью окна в панели задач и «спрятать в трей»,
// перетаскивание файлов (OLE), а также основа COM (GUID, HRESULT, таблицы
// методов) для возможностей вне пакета. Системная тема и акцент — службы
// оболочки, platform/shell; иконка в трее и уведомления — platform/tray.
//
// Точки расширения для возможностей вне бэкенда: AddMessageHook — обработчик
// оконного сообщения (доступность UI Automation, platform/a11y, отвечает
// так на WM_GETOBJECT; службы оболочки, platform/shell, следят так за
// WM_SETTINGCHANGE — сменой темы и акцента; трей, platform/tray, получает так
// события иконки — WM_APP+1 — и WM_DESTROY), Win32Window.HWND — дескриптор
// окна, WindowOf — окно бэкенда по дескриптору (и создаваемое окно, пока
// CreateWindowExW не вернул дескриптор): по нему обработчик сообщения находит
// своё состояние окна; NewIcon — HICON из картинки (иконка трея).
//
// Программы этот пакет не импортируют: Win32Window, NewNativeWindow и
// AllowForeground приходят через фасад window. Пакет собирается и на других
// ОС (только переносимые помощники с тестами), но окна там нет.
