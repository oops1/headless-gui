// Package testengine — движок для тестов соседних пакетов.
//
// Движок при создании регистрирует себя в общих реестрах пакета widget:
// приёмников уведомлений об изменениях и измерителей текста, где действующим
// считается ПОСЛЕДНИЙ зарегистрированный. Снимается он только в Stop. Тест,
// создавший движок и не остановивший его, оставляет там мёртвый холст: чужие
// тесты меряют текст его шрифтами и рассылают инвалидации в никуда, а число
// кадров и аллокаций зависит от того, сколько таких движков накопилось, то
// есть от порядка запуска (go test -shuffle=on).
package testengine

import (
	"testing"

	"github.com/oops1/headless-gui/v4/engine"
)

// New создаёт движок и останавливает его по окончании теста. Stop идемпотентен
// и безопасен без Start, поэтому тест, остановивший движок сам, ничего не
// теряет.
func New(t testing.TB, width, height, fps int) *engine.Engine {
	t.Helper()
	eng := engine.New(width, height, fps)
	t.Cleanup(eng.Stop)
	return eng
}
