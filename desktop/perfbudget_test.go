package desktop_test

import (
	"os"
	"strconv"
	"time"
)

// perfBudget — порог для тестов скорости по стенным часам.
//
// Локально порог тот, что записан в тесте. Машины CI (GitHub Actions
// выставляет CI=true) в разы медленнее и делят процессор с соседями: кадр
// «Пуска», который здесь рисуется за 8 мс, там шёл 84 мс, и тест падал без
// всякого дефекта. Такие тесты ловят патологию — кадр в разы дороже, чем
// должен быть, — а не колебания чужого железа, поэтому под CI порог
// умножается (по умолчанию на 4; HG_PERF_SLACK задаёт множитель явно).
//
// Детектор гонок (-race) замедляет код в разы сам по себе — кадр анимации
// боковой панели «Пуска» под ним шёл дольше 50 мс без всякого дефекта, — и
// тот же замер говорит уже о цене инструментирования. Под -race порог
// умножается ещё на raceSlack: патологию «в разы дороже» тест ловит и там.
func perfBudget(base time.Duration) time.Duration {
	if raceEnabled {
		base *= raceSlack
	}
	if s := os.Getenv("HG_PERF_SLACK"); s != "" {
		if k, err := strconv.ParseFloat(s, 64); err == nil && k > 0 {
			return time.Duration(float64(base) * k)
		}
	}
	if os.Getenv("CI") != "" {
		return base * 4
	}
	return base
}

// raceSlack — во сколько раз под -race ослаблен порог perfBudget.
const raceSlack = 10

// bestOf повторяет замер n раз и возвращает лучший.
//
// Одиночный замер на машине CI ловит не цену кода, а паузы планировщика:
// тёплый кадр меню «Пуск» однажды вышел 411 мс при холодном 201 мс — вдвое
// медленнее первого, хотя кэши уже заполнены. Лучший из нескольких порог не
// смягчает: если кадр и правда стал дороже предела, дороже будет каждый
// повтор. Так меряют то, что повторяется; холодный замер — одноразовый по
// природе и остаётся одиночным.
func bestOf(n int, measure func() time.Duration) time.Duration {
	best := measure()
	for i := 1; i < n; i++ {
		if d := measure(); d < best {
			best = d
		}
	}
	return best
}
