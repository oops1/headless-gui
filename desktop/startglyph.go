var (
	glyphMu   sync.Mutex
	glyphDocs = map[StartGlyph]*svg.Document{}
)

// glyphDoc разбирает SVG значка один раз.
func glyphDoc(g StartGlyph) *svg.Document {
	glyphMu.Lock()
	defer glyphMu.Unlock()
	if d, ok := glyphDocs[g]; ok {
		return d
	}
	var doc *svg.Document
	if d, ok := glyphPaths[g]; ok {
		doc, _ = svg.Parse([]byte(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="currentColor" fill-rule="evenodd" d="` + d + `"/></svg>`))
	}
	glyphDocs[g] = doc
	return doc
}

// drawGlyph рисует встроенный значок в логическом квадрате r цветом col.
func drawGlyph(ctx widget.DrawContext, g StartGlyph, r image.Rectangle, col color.RGBA) {
	widget.DrawSVG(ctx, glyphDoc(g), r, col, true)
}
